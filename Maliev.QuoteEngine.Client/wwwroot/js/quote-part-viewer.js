// ── resetCamera ───────────────────────────────────────────────────────────────

export function resetCamera(canvasId, smooth = true) {
    const cam = mainCameras[canvasId];
    const bb  = sceneBoundingBoxes[canvasId];
    if (!cam) return;

    // Kill auto-rotation instantly
    autoSpeedCurrent[canvasId] = 0;
    autoSpeedTarget[canvasId]  = SPEED_STOP;
    animStates[canvasId]       = 'interacting';

    // Reset orthographic zoom factor to prevent feedback loop
    orthoZoomFactors[canvasId] = 1.0;

    cam.upVector = new BABYLON.Vector3(0, 0, 1);
    if (bb) fitCameraToMesh(cam, bb, meshCenters[canvasId], canvasId);
    applyPreset(cam, 'iso', smooth, canvasId);

    const canvas = document.getElementById(canvasId);
    if (canvas && !cam.inputs.attached.keyboard) cam.attachControl(canvas, true);
}

