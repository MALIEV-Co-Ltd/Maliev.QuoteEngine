function disposeSectionVisuals(canvasId, scene = scenes[canvasId]) {
    if (sectionEdgeMeshes[canvasId]) {
        sectionEdgeMeshes[canvasId].dispose();
        sectionEdgeMeshes[canvasId] = null;
    }
    if (sectionHatchMeshes[canvasId]) {
        sectionHatchMeshes[canvasId].dispose();
        sectionHatchMeshes[canvasId] = null;
    }
    if (sectionFillMeshes[canvasId]) {
        sectionFillMeshes[canvasId].dispose();
        sectionFillMeshes[canvasId] = null;
    }
    if (sectionObservers[canvasId]) {
        if (scene) scene.onBeforeRenderObservable.remove(sectionObservers[canvasId]);
        sectionObservers[canvasId] = null;
    }
    _disposeSectionGhosts(canvasId);
    _sectionRebuildPending[canvasId] = false;
}

function configureSectionLineMesh(mesh, color) {
    if (!mesh) return mesh;
    mesh.color = toColor3(color);
    mesh.renderingGroupId = CONFIG.SECTION.renderingGroupId;
    mesh.alwaysSelectAsActiveMesh = true;

    if (mesh.material) {
        mesh.material.disableClipPlanes = true;
        mesh.material.disableDepthWrite = false;
        mesh.material.disableDepthTest = false;
        mesh.material.forceDepthWrite = true;
        mesh.material.needDepthPrePass = false;
        mesh.material.zOffset = CONFIG.SECTION.zOffset;
    }

    return markAnalysisHelperMesh(mesh);
}

function disableSectionClippingForMesh(mesh) {
    if (mesh?.material) {
        mesh.material.disableClipPlanes = true;
    }
}

function forEachMeshMaterial(mesh, callback) {
    const material = mesh?.material;
    if (!material) return;

    callback(material);
    if (Array.isArray(material.subMaterials)) {
        material.subMaterials.forEach(subMaterial => {
            if (subMaterial) callback(subMaterial);
        });
    }
}

function clearSectionClippingForModelMeshes(canvasId, scene) {
    if (!scene?.meshes) return;

    for (const mesh of scene.meshes) {
        if (!isModelMeshForAnalysis(mesh, canvasId)) continue;
        forEachMeshMaterial(mesh, material => {
            if (material._malievSectionClip === true) {
                material.clipPlane = null;
                material._malievSectionClip = false;
            }
        });
    }
    sectionClipPlanes[canvasId] = null;
}

function applySectionClippingToModelMeshes(canvasId, scene, plane) {
    if (!scene?.meshes || !plane) return;

    for (const mesh of scene.meshes) {
        if (!isModelMeshForAnalysis(mesh, canvasId)) continue;
        forEachMeshMaterial(mesh, material => {
            material.clipPlane = plane;
            material.disableClipPlanes = false;
            material._malievSectionClip = true;
        });
    }
    sectionClipPlanes[canvasId] = plane;
}

function disableSectionClippingForSystemMeshes(canvasId, scene) {
    if (!scene?.meshes) return;

    for (const mesh of scene.meshes) {
        if (!mesh?.material) continue;
        if (isModelMeshForAnalysis(mesh, canvasId)) continue;
        disableSectionClippingForMesh(mesh);
    }
}

function scheduleSectionRebuild(canvasId, scene, planeNormal, planeD) {
    if (_sectionRebuildPending[canvasId]) return;
    _sectionRebuildPending[canvasId] = true;
    requestAnimationFrame(() => {
        _sectionRebuildPending[canvasId] = false;
        if (scenes[canvasId] !== scene || !sectionClipPlanes[canvasId]) return;
        _rebuildSectionFill(canvasId, scene, planeNormal, planeD);
        _rebuildSectionEdges(canvasId, scene, planeNormal, planeD);
        _rebuildSectionHatch(canvasId, scene, planeNormal, planeD);
    });
}

/**
 * Sets or clears the scene clipping plane and redraws the cut-edge lines.
 * offsetMm is measured from the model centre along the chosen axis (so 0 = centre).
 * @param {string}  canvasId
 * @param {boolean} enabled
 * @param {string}  axis      "x" | "y" | "z"
 * @param {number}  offsetMm  mm from model centre (positive = toward max extent)
 * @param {boolean} inverted  flip which half is kept
 */
export function setSectionPlane(canvasId, enabled, axis, offsetMm, inverted) {
    const scene = scenes[canvasId];
    if (!scene) return;

    disposeSectionVisuals(canvasId, scene);
    clearSectionClippingForModelMeshes(canvasId, scene);
    scene.clipPlane = null;

    if (!enabled) {
        return;
    }

    ensureModelMeshesTagged(canvasId, scene);

    // World coordinate of the clipping plane along the chosen axis.
    // Model centre along each axis (from meshCenters, which stores the post-centering centre):
    //   X, Y ≈ 0 (model is centred at world origin in X/Y)
    //   Z ≈ boundingBoxZ/2 (build-plate is at Z=0, model top at Z=height)
    const scaleFactor = modelScaleFactors[canvasId] ?? 1;
    const mc = meshCenters[canvasId] ?? { x: 0, y: 0, z: 0 };
    const axisCenter = axis === 'x' ? mc.x : (axis === 'y' ? mc.y : mc.z);
    const worldOffset = axisCenter + offsetMm * scaleFactor;

    const defaultSign = axis === 'x' || axis === 'y' ? -1 : 1;
    const sign = inverted ? -defaultSign : defaultSign;
    let nx = 0, ny = 0, nz = 0;
    switch (axis) {
        case 'x': nx = sign; break;
        case 'y': ny = sign; break;
        case 'z': nz = sign; break;
        default:  nx = sign; break;
    }
    const d = -(nx * worldOffset + ny * worldOffset + nz * worldOffset);
    const plane = new BABYLON.Plane(nx, ny, nz, d);
    applySectionClippingToModelMeshes(canvasId, scene, plane);
    disableSectionClippingForSystemMeshes(canvasId, scene);

    // Create ghost clones for the hidden half (xray silhouette)
    _createSectionGhosts(canvasId, scene, nx, ny, nz, d);

    scheduleSectionRebuild(canvasId, scene, new BABYLON.Vector3(nx, ny, nz), d);
}

/**
 * Computes triangle/plane intersection segments for every visible non-overlay mesh,
 * builds a LinesMesh coloured like the model edges, and stores it in sectionEdgeMeshes.
 * @param {string}               canvasId
 * @param {BABYLON.Scene}        scene
 * @param {BABYLON.Vector3}      planeNormal  world-space normal (unit axis vector)
 * @param {number}               planeD       plane constant (n·p + d = 0)
 */
function _rebuildSectionEdges(canvasId, scene, planeNormal, planeD) {
    if (sectionEdgeMeshes[canvasId]) {
        sectionEdgeMeshes[canvasId].dispose();
        sectionEdgeMeshes[canvasId] = null;
    }

    const lines = [];

    for (const mesh of scene.meshes) {
        if (!mesh.isVisible || !isModelMeshForAnalysis(mesh, canvasId)) continue;

        const positions = mesh.getVerticesData(BABYLON.VertexBuffer.PositionKind);
        const indices = mesh.getIndices();
        if (!positions || !indices || indices.length === 0) continue;

        const worldMatrix = mesh.getWorldMatrix();

        for (let i = 0; i < indices.length; i += 3) {
            const i0 = indices[i], i1 = indices[i + 1], i2 = indices[i + 2];

            // Transform to world space
            const wv0 = BABYLON.Vector3.TransformCoordinates(
                new BABYLON.Vector3(positions[i0 * 3], positions[i0 * 3 + 1], positions[i0 * 3 + 2]),
                worldMatrix);
            const wv1 = BABYLON.Vector3.TransformCoordinates(
                new BABYLON.Vector3(positions[i1 * 3], positions[i1 * 3 + 1], positions[i1 * 3 + 2]),
                worldMatrix);
            const wv2 = BABYLON.Vector3.TransformCoordinates(
                new BABYLON.Vector3(positions[i2 * 3], positions[i2 * 3 + 1], positions[i2 * 3 + 2]),
                worldMatrix);

            // Signed distances to plane
            const d0 = BABYLON.Vector3.Dot(planeNormal, wv0) + planeD;
            const d1 = BABYLON.Vector3.Dot(planeNormal, wv1) + planeD;
            const d2 = BABYLON.Vector3.Dot(planeNormal, wv2) + planeD;

            // Collect edge crossings (sign change = the edge crosses the plane)
            const pts = [];
            const edges = [[wv0, wv1, d0, d1], [wv1, wv2, d1, d2], [wv2, wv0, d2, d0]];
            for (const [va, vb, da, db] of edges) {
                if (da * db < 0) {
                    const t = -da / (db - da);
                    pts.push(BABYLON.Vector3.Lerp(va, vb, t));
                }
            }

            if (pts.length === 2) {
                lines.push([pts[0], pts[1]]);
            }
        }
    }

    if (lines.length === 0) return;

    const linesMesh = BABYLON.MeshBuilder.CreateLineSystem(
        `__section_edges_${canvasId}__`,
        { lines, updatable: false },
        scene
    );
    configureSectionLineMesh(linesMesh, CONFIG.SECTION.cutEdgeColor);
    sectionEdgeMeshes[canvasId] = linesMesh;
}

function collectSectionSegments(canvasId, scene, planeNormal, planeD) {
    const segments = [];

    for (const mesh of scene.meshes) {
        if (!mesh.isVisible || !isModelMeshForAnalysis(mesh, canvasId)) continue;

        const positions = mesh.getVerticesData(BABYLON.VertexBuffer.PositionKind);
        const indices = mesh.getIndices();
        if (!positions || !indices || indices.length === 0) continue;

        const worldMatrix = mesh.getWorldMatrix();

        for (let i = 0; i < indices.length; i += 3) {
            const i0 = indices[i], i1 = indices[i + 1], i2 = indices[i + 2];
            const wv0 = BABYLON.Vector3.TransformCoordinates(
                new BABYLON.Vector3(positions[i0 * 3], positions[i0 * 3 + 1], positions[i0 * 3 + 2]), worldMatrix);
            const wv1 = BABYLON.Vector3.TransformCoordinates(
                new BABYLON.Vector3(positions[i1 * 3], positions[i1 * 3 + 1], positions[i1 * 3 + 2]), worldMatrix);
            const wv2 = BABYLON.Vector3.TransformCoordinates(
                new BABYLON.Vector3(positions[i2 * 3], positions[i2 * 3 + 1], positions[i2 * 3 + 2]), worldMatrix);

            const d0 = BABYLON.Vector3.Dot(planeNormal, wv0) + planeD;
            const d1 = BABYLON.Vector3.Dot(planeNormal, wv1) + planeD;
            const d2 = BABYLON.Vector3.Dot(planeNormal, wv2) + planeD;

            const pts = [];
            const edges = [[wv0, wv1, d0, d1], [wv1, wv2, d1, d2], [wv2, wv0, d2, d0]];
            for (const [va, vb, da, db] of edges) {
                if (da * db < 0) {
                    const t = -da / (db - da);
                    pts.push(BABYLON.Vector3.Lerp(va, vb, t));
                }
            }
            if (pts.length === 2) segments.push([pts[0], pts[1]]);
        }
    }

    return segments;
}

function getSectionPlaneAxes(planeNormal) {
    let uAxis, vAxis;
    const absX = Math.abs(planeNormal.x), absY = Math.abs(planeNormal.y), absZ = Math.abs(planeNormal.z);
    if (absX <= absY && absX <= absZ) {
        uAxis = new BABYLON.Vector3(1, 0, 0);
    } else if (absY <= absZ) {
        uAxis = new BABYLON.Vector3(0, 1, 0);
    } else {
        uAxis = new BABYLON.Vector3(0, 0, 1);
    }
    vAxis = BABYLON.Vector3.Cross(planeNormal, uAxis);
    vAxis.normalize();
    uAxis = BABYLON.Vector3.Cross(vAxis, planeNormal);
    uAxis.normalize();
    return { uAxis, vAxis };
}

function pointOnSectionPlane(u, v, uAxis, vAxis, planeNormal, planeD) {
    return new BABYLON.Vector3(
        u * uAxis.x + v * vAxis.x - planeD * planeNormal.x,
        u * uAxis.y + v * vAxis.y - planeD * planeNormal.y,
        u * uAxis.z + v * vAxis.z - planeD * planeNormal.z
    );
}

function _rebuildSectionFill(canvasId, scene, planeNormal, planeD) {
    if (sectionFillMeshes[canvasId]) {
        sectionFillMeshes[canvasId].dispose();
        sectionFillMeshes[canvasId] = null;
    }

    const allSegments = collectSectionSegments(canvasId, scene, planeNormal, planeD);
    if (allSegments.length === 0) return;

    const { uAxis, vAxis } = getSectionPlaneAxes(planeNormal);
    const scaleFactor = modelScaleFactors[canvasId] ?? 1;
    const planeLift = planeNormal.scale(CONFIG.SECTION.planeLiftMm * 0.2 * scaleFactor);
    const segments2D = [];
    let minV = Infinity;
    let maxV = -Infinity;

    for (const [p0, p1] of allSegments) {
        const u0 = BABYLON.Vector3.Dot(p0, uAxis);
        const v0 = BABYLON.Vector3.Dot(p0, vAxis);
        const u1 = BABYLON.Vector3.Dot(p1, uAxis);
        const v1 = BABYLON.Vector3.Dot(p1, vAxis);
        segments2D.push({ u0, v0, u1, v1 });
        minV = Math.min(minV, v0, v1);
        maxV = Math.max(maxV, v0, v1);
    }

    if (!Number.isFinite(minV) || !Number.isFinite(maxV)) return;

    const spanV = Math.max(maxV - minV, CONFIG.SECTION.minHatchSpacing);
    const fillStep = Math.max(Math.min(spanV / 120, 1.1 * scaleFactor), 0.35 * scaleFactor);
    const halfBand = fillStep * 0.48;
    const epsilon = 1e-5;
    const positions = [];
    const indices = [];

    for (let v = minV + fillStep / 2; v <= maxV - fillStep / 2 + epsilon; v += fillStep) {
        const intersections = [];
        for (const segment of segments2D) {
            const vMin = Math.min(segment.v0, segment.v1);
            const vMax = Math.max(segment.v0, segment.v1);
            if (v < vMin - epsilon || v > vMax + epsilon) continue;
            const dv = segment.v1 - segment.v0;
            if (Math.abs(dv) <= epsilon) continue;
            const t = (v - segment.v0) / dv;
            if (t < -epsilon || t > 1 + epsilon) continue;
            intersections.push(segment.u0 + t * (segment.u1 - segment.u0));
        }

        intersections.sort((a, b) => a - b);
        const unique = [];
        for (const value of intersections) {
            if (unique.length === 0 || Math.abs(value - unique[unique.length - 1]) > epsilon * 10) {
                unique.push(value);
            }
        }

        for (let i = 0; i < unique.length - 1; i += 2) {
            const u0 = unique[i];
            const u1 = unique[i + 1];
            if (!Number.isFinite(u0) || !Number.isFinite(u1) || Math.abs(u1 - u0) <= epsilon) continue;
            const v0 = Math.max(minV, v - halfBand);
            const v1 = Math.min(maxV, v + halfBand);
            const p0 = pointOnSectionPlane(u0, v0, uAxis, vAxis, planeNormal, planeD).addInPlace(planeLift);
            const p1 = pointOnSectionPlane(u1, v0, uAxis, vAxis, planeNormal, planeD).addInPlace(planeLift);
            const p2 = pointOnSectionPlane(u1, v1, uAxis, vAxis, planeNormal, planeD).addInPlace(planeLift);
            const p3 = pointOnSectionPlane(u0, v1, uAxis, vAxis, planeNormal, planeD).addInPlace(planeLift);
            const vertexOffset = positions.length / 3;
            positions.push(
                p0.x, p0.y, p0.z,
                p1.x, p1.y, p1.z,
                p2.x, p2.y, p2.z,
                p3.x, p3.y, p3.z);
            indices.push(vertexOffset, vertexOffset + 1, vertexOffset + 2, vertexOffset, vertexOffset + 2, vertexOffset + 3);
        }
    }

    if (positions.length === 0 || indices.length === 0) return;

    const fillMesh = new BABYLON.Mesh(`__section_fill_${canvasId}__`, scene);
    const vertexData = new BABYLON.VertexData();
    vertexData.positions = positions;
    vertexData.indices = indices;
    vertexData.applyToMesh(fillMesh);

    const fillMat = new BABYLON.StandardMaterial(`__section_fill_mat_${canvasId}__`, scene);
    fillMat.diffuseColor = toColor3(CONFIG.SECTION.fillColor);
    fillMat.emissiveColor = toColor3(CONFIG.SECTION.fillColor);
    fillMat.ambientColor = toColor3(CONFIG.SECTION.fillColor);
    fillMat.specularColor = new BABYLON.Color3(0, 0, 0);
    fillMat.alpha = CONFIG.SECTION.fillAlpha;
    fillMat.backFaceCulling = false;
    fillMat.disableLighting = true;
    fillMat.disableClipPlanes = true;
    fillMat.disableDepthWrite = false;
    fillMat.disableDepthTest = false;
    fillMat.forceDepthWrite = true;
    fillMat.needDepthPrePass = false;
    fillMat.zOffset = CONFIG.SECTION.zOffset - 1;
    fillMesh.material = fillMat;
    fillMesh.renderingGroupId = CONFIG.SECTION.renderingGroupId;
    fillMesh.alwaysSelectAsActiveMesh = true;
    sectionFillMeshes[canvasId] = markAnalysisHelperMesh(fillMesh);
    sectionFillMeshes[canvasId].metadata = {
        ...(sectionFillMeshes[canvasId].metadata ?? {}),
        sectionFillMode: 'scanline-bands',
    };
}

/**
 * Draws parallel diagonal hatch lines clipped to the section polygon.
 * This creates the traditional engineering cross-section fill pattern.
 */
function _rebuildSectionHatch(canvasId, scene, planeNormal, planeD) {
    if (sectionHatchMeshes[canvasId]) {
        sectionHatchMeshes[canvasId].dispose();
        sectionHatchMeshes[canvasId] = null;
    }

    // Collect all intersection points as line segments
    const allSegments = [];
    for (const mesh of scene.meshes) {
        if (!mesh.isVisible || !isModelMeshForAnalysis(mesh, canvasId)) continue;

        const positions = mesh.getVerticesData(BABYLON.VertexBuffer.PositionKind);
        const indices = mesh.getIndices();
        if (!positions || !indices || indices.length === 0) continue;

        const worldMatrix = mesh.getWorldMatrix();

        for (let i = 0; i < indices.length; i += 3) {
            const i0 = indices[i], i1 = indices[i + 1], i2 = indices[i + 2];
            const wv0 = BABYLON.Vector3.TransformCoordinates(
                new BABYLON.Vector3(positions[i0 * 3], positions[i0 * 3 + 1], positions[i0 * 3 + 2]), worldMatrix);
            const wv1 = BABYLON.Vector3.TransformCoordinates(
                new BABYLON.Vector3(positions[i1 * 3], positions[i1 * 3 + 1], positions[i1 * 3 + 2]), worldMatrix);
            const wv2 = BABYLON.Vector3.TransformCoordinates(
                new BABYLON.Vector3(positions[i2 * 3], positions[i2 * 3 + 1], positions[i2 * 3 + 2]), worldMatrix);

            const d0 = BABYLON.Vector3.Dot(planeNormal, wv0) + planeD;
            const d1 = BABYLON.Vector3.Dot(planeNormal, wv1) + planeD;
            const d2 = BABYLON.Vector3.Dot(planeNormal, wv2) + planeD;

            const pts = [];
            const edges = [[wv0, wv1, d0, d1], [wv1, wv2, d1, d2], [wv2, wv0, d2, d0]];
            for (const [va, vb, da, db] of edges) {
                if (da * db < 0) {
                    const t = -da / (db - da);
                    pts.push(BABYLON.Vector3.Lerp(va, vb, t));
                }
            }
            if (pts.length === 2) {
                allSegments.push([pts[0], pts[1]]);
            }
        }
    }

    if (allSegments.length === 0) return;

    // Project all intersection points to 2D on the section plane.
    const { uAxis, vAxis } = getSectionPlaneAxes(planeNormal);

    // Compute 2D bounding box of all intersection points
    let minU = Infinity, maxU = -Infinity, minV = Infinity, maxV = -Infinity;
    const points2D = [];
    for (const seg of allSegments) {
        for (const p of seg) {
            const pu = BABYLON.Vector3.Dot(p, uAxis);
            const pv = BABYLON.Vector3.Dot(p, vAxis);
            minU = Math.min(minU, pu);
            maxU = Math.max(maxU, pu);
            minV = Math.min(minV, pv);
            maxV = Math.max(maxV, pv);
            points2D.push({ u: pu, v: pv });
        }
    }

    // Generate diagonal cross-hatch lines across the actual projected contour,
    // not around world zero. Model Z is intentionally lifted above the floor.
    const hatchSpacing = Math.max(
        CONFIG.SECTION.hatchSpacingMm * (modelScaleFactors[canvasId] ?? 1),
        CONFIG.SECTION.minHatchSpacing);
    const hatchAngles = [Math.PI / 4];
    const hatchLines = [];

    const planeLift = planeNormal.scale(CONFIG.SECTION.planeLiftMm * (modelScaleFactors[canvasId] ?? 1));
    const hatchEpsilon = 1e-5;

    for (const hatchAngle of hatchAngles) {
        const cosA = Math.cos(hatchAngle);
        const sinA = Math.sin(hatchAngle);
        const perpU = -sinA;
        const perpV = cosA;

        let minOffset = Infinity;
        let maxOffset = -Infinity;
        for (const point of points2D) {
            const value = perpU * point.u + perpV * point.v;
            minOffset = Math.min(minOffset, value);
            maxOffset = Math.max(maxOffset, value);
        }

        const startOffset = Math.floor((minOffset - hatchSpacing) / hatchSpacing) * hatchSpacing;
        const endOffset = Math.ceil((maxOffset + hatchSpacing) / hatchSpacing) * hatchSpacing;

        for (let offset = startOffset; offset <= endOffset; offset += hatchSpacing) {
            const intersectPts = [];
            for (const seg of allSegments) {
                const u0 = BABYLON.Vector3.Dot(seg[0], uAxis);
                const v0 = BABYLON.Vector3.Dot(seg[0], vAxis);
                const u1 = BABYLON.Vector3.Dot(seg[1], uAxis);
                const v1 = BABYLON.Vector3.Dot(seg[1], vAxis);

                const d0 = perpU * u0 + perpV * v0 - offset;
                const d1 = perpU * u1 + perpV * v1 - offset;
                if (Math.abs(d0) <= hatchEpsilon && Math.abs(d1) <= hatchEpsilon) continue;

                if ((d0 < -hatchEpsilon && d1 > hatchEpsilon)
                    || (d0 > hatchEpsilon && d1 < -hatchEpsilon)
                    || Math.abs(d0) <= hatchEpsilon
                    || Math.abs(d1) <= hatchEpsilon) {
                    const denominator = d1 - d0;
                    if (Math.abs(denominator) <= hatchEpsilon) continue;
                    const t = Math.max(0, Math.min(1, -d0 / denominator));
                    const hu = u0 + t * (u1 - u0);
                    const hv = v0 + t * (v1 - v0);
                    intersectPts.push({ u: hu, v: hv, s: cosA * hu + sinA * hv });
                }
            }

            if (intersectPts.length >= 2) {
                intersectPts.sort((a, b) => a.s - b.s);
                const uniquePts = [];
                for (const point of intersectPts) {
                    if (uniquePts.length === 0 || Math.abs(point.s - uniquePts[uniquePts.length - 1].s) > hatchEpsilon * 10) {
                        uniquePts.push(point);
                    }
                }

                for (let i = 0; i < uniquePts.length - 1; i += 2) {
                    const p1 = uniquePts[i];
                    const p2 = uniquePts[i + 1];
                    const pt1 = new BABYLON.Vector3(
                        p1.u * uAxis.x + p1.v * vAxis.x - planeD * planeNormal.x,
                        p1.u * uAxis.y + p1.v * vAxis.y - planeD * planeNormal.y,
                        p1.u * uAxis.z + p1.v * vAxis.z - planeD * planeNormal.z
                    ).addInPlace(planeLift);
                    const pt2 = new BABYLON.Vector3(
                        p2.u * uAxis.x + p2.v * vAxis.x - planeD * planeNormal.x,
                        p2.u * uAxis.y + p2.v * vAxis.y - planeD * planeNormal.y,
                        p2.u * uAxis.z + p2.v * vAxis.z - planeD * planeNormal.z
                    ).addInPlace(planeLift);
                    hatchLines.push([pt1, pt2]);
                }
            }
        }
    }

    if (hatchLines.length === 0) return;

    const hatchWidth = Math.max(
        CONFIG.SECTION.hatchWidthMm * (modelScaleFactors[canvasId] ?? 1),
        0.02);
    const hatchLift = planeNormal.scale(CONFIG.SECTION.planeLiftMm * 0.8 * (modelScaleFactors[canvasId] ?? 1));
    const stripPaths = [];
    const positions = [];
    const indices = [];

    for (const [baseStart, baseEnd] of hatchLines) {
        const direction = baseEnd.subtract(baseStart);
        if (direction.length() <= 1e-6) continue;
        direction.normalize();

        const widthAxis = BABYLON.Vector3.Cross(planeNormal, direction);
        if (widthAxis.length() <= 1e-6) continue;
        widthAxis.normalize();
        const halfWidth = widthAxis.scale(hatchWidth / 2);

        const start = baseStart.add(hatchLift);
        const end = baseEnd.add(hatchLift);
        const p0 = start.add(halfWidth);
        const p1 = start.subtract(halfWidth);
        const p2 = end.subtract(halfWidth);
        const p3 = end.add(halfWidth);
        const vertexOffset = positions.length / 3;
        positions.push(
            p0.x, p0.y, p0.z,
            p1.x, p1.y, p1.z,
            p2.x, p2.y, p2.z,
            p3.x, p3.y, p3.z);
        indices.push(
            vertexOffset, vertexOffset + 1, vertexOffset + 2,
            vertexOffset, vertexOffset + 2, vertexOffset + 3);
        stripPaths.push([p0, p1, p2, p3]);
    }

    if (positions.length === 0) return;

    const hatchMesh = new BABYLON.Mesh(`__section_hatch_${canvasId}__`, scene);
    const vertexData = new BABYLON.VertexData();
    vertexData.positions = positions;
    vertexData.indices = indices;
    vertexData.applyToMesh(hatchMesh);
    hatchMesh.pathArray = stripPaths;

    const hatchMat = new BABYLON.StandardMaterial(`__section_hatch_mat_${canvasId}__`, scene);
    hatchMat.diffuseColor = toColor3(CONFIG.SECTION.hatchColor);
    hatchMat.emissiveColor = toColor3(CONFIG.SECTION.hatchColor);
    hatchMat.ambientColor = toColor3(CONFIG.SECTION.hatchColor);
    hatchMat.specularColor = new BABYLON.Color3(0, 0, 0);
    hatchMat.backFaceCulling = false;
    hatchMat.disableLighting = true;
    hatchMesh.material = hatchMat;

    configureSectionLineMesh(hatchMesh, CONFIG.SECTION.hatchColor);
    sectionHatchMeshes[canvasId] = hatchMesh;
}

// ── rotateModel ─────────────────────────────────────────────────────────────────

export function rotateModel(canvasId, degrees, smooth = true) {
    const scene = scenes[canvasId];
    if (!scene) return;
    const cam = mainCameras[canvasId];
    if (!cam || !(cam instanceof BABYLON.ArcRotateCamera)) return;

    // Kill auto-rotation instantly
    autoSpeedCurrent[canvasId] = 0;
    autoSpeedTarget[canvasId]  = SPEED_STOP;
    animStates[canvasId]       = 'interacting';

    const rad = degrees * Math.PI / 180;

    // Use smooth animation for 90-degree rotations (or multiples thereof)
    if (smooth && Math.abs(degrees % 90) < 0.001) {
        animateCameraAlpha(cam, rad);
    } else {
        // Immediate rotation for non-90-degree angles
        cam.alpha += rad;
    }
}

// ── zoomTo ────────────────────────────────────────────────────────────────────────

/**
 * Smoothly zooms the camera to a target zoom factor.
 * @param {string} canvasId - Canvas identifier
 * @param {number} zoomFactor - Target zoom factor (1.0 = fit to view, <1 = zoomed in, >1 = zoomed out)
 * @param {boolean} smooth - Whether to animate the transition (default: true)
 */
export function zoomTo(canvasId, zoomFactor, smooth = true) {
    const cam = mainCameras[canvasId];
    const scene = scenes[canvasId];
    if (!cam || !scene) return;

    // Kill auto-rotation instantly
    autoSpeedCurrent[canvasId] = 0;
    autoSpeedTarget[canvasId]  = SPEED_STOP;
    animStates[canvasId]       = 'interacting';

    const initialRadius = fitRadiusMap[canvasId];
    if (!initialRadius) return;

    if (cameraProjection[canvasId] === 'orthographic') {
        // Orthographic mode: animate the zoom factor
        const currentZoomFactor = orthoZoomFactors[canvasId] || 1.0;
        const targetZoomFactor = Math.max(0.01, Math.min(100, zoomFactor)); // Clamp between 1% and 100x

        if (smooth && currentZoomFactor !== targetZoomFactor) {
            const duration = CONFIG.CAMERA_TRANSITION_DURATION * 1000;
            const startZoom = currentZoomFactor;
            const startTime = performance.now();

            const anim = () => {
                const elapsed = performance.now() - startTime;
                const progress = Math.min(elapsed / duration, 1);
                const eased = easeInOutCubic(progress);

                const newZoomFactor = startZoom + (targetZoomFactor - startZoom) * eased;
                orthoZoomFactors[canvasId] = newZoomFactor;

                // Update ortho bounds
                const engine = engines[canvasId];
                if (engine) {
                    const asp = engine.getAspectRatio(cam);
                    const h = initialRadius * newZoomFactor * ORTHO_RADIUS_FACTOR;
                    cam.orthoLeft   = -h * asp;
                    cam.orthoRight  =  h * asp;
                    cam.orthoTop    =  h;
                    cam.orthoBottom = -h;
                }

                if (progress < 1) {
                    requestAnimationFrame(anim);
                }
            };
            anim();
        } else {
            // Immediate zoom
            orthoZoomFactors[canvasId] = targetZoomFactor;
            const engine = engines[canvasId];
            if (engine) {
                const asp = engine.getAspectRatio(cam);
                const h = initialRadius * targetZoomFactor * ORTHO_RADIUS_FACTOR;
                cam.orthoLeft   = -h * asp;
                cam.orthoRight  =  h * asp;
                cam.orthoTop    =  h;
                cam.orthoBottom = -h;
            }
        }
    } else {
        // Perspective mode: animate the camera radius
        const targetRadius = initialRadius * Math.max(0.01, Math.min(100, zoomFactor));

        if (smooth && Math.abs(cam.radius - targetRadius) > 0.001) {
            animateCameraRadius(cam, targetRadius);
        } else {
            cam.radius = targetRadius;
        }
    }
}

/**
 * Resets zoom to fit the model in view (zoomFactor = 1.0).
 * @param {string} canvasId - Canvas identifier
 * @param {boolean} smooth - Whether to animate the transition (default: true)
 */
export function zoomToFit(canvasId, smooth = true) {
    zoomTo(canvasId, 1.0, smooth);
}

// ── dispose ───────────────────────────────────────────────────────────────────

export function dispose(canvasId) {
    loadGenerations[canvasId] = (loadGenerations[canvasId] || 0) + 1;

    const engine = engines[canvasId];
    if (engine?._resizeHandler) window.removeEventListener('resize', engine._resizeHandler);
    try { engine?.stopRenderLoop(); } catch (_) {}

    clearTurningAxis(canvasId);
    if (resizeObservers[canvasId]) { resizeObservers[canvasId].disconnect(); delete resizeObservers[canvasId]; }
    if (axisGizmoLayer[canvasId])  { try { axisGizmoLayer[canvasId].dispose(); } catch (_) {} delete axisGizmoLayer[canvasId]; }
    if (axisLabelDivs[canvasId])   { axisLabelDivs[canvasId].forEach(({ div }) => div.remove()); delete axisLabelDivs[canvasId]; }

    const canvas = document.getElementById(canvasId);
    if (canvas) {
        if (axisMouseHandlers[canvasId])              canvas.removeEventListener('mousemove',  axisMouseHandlers[canvasId]);
        if (axisMouseHandlers[canvasId + '_leave'])   canvas.removeEventListener('mouseleave', axisMouseHandlers[canvasId + '_leave']);
    }
    delete axisMouseHandlers[canvasId];
    delete axisMouseHandlers[canvasId + '_leave'];

    // Clean up custom right-click pan handlers
    const panH = panHandlers[canvasId];
    if (panH && canvas) {
        canvas.removeEventListener('pointerdown',  panH.down);
        canvas.removeEventListener('pointermove',  panH.move);
        canvas.removeEventListener('pointerup',    panH.up);
        canvas.removeEventListener('contextmenu',  panH.ctx);
    }
    delete panHandlers[canvasId];
    delete panStates[canvasId];

    // Clean up middle-mouse zoom handlers
    const midH = middleZoomHandlers[canvasId];
    if (midH && canvas) {
        canvas.removeEventListener('pointerdown',  midH.down);
        canvas.removeEventListener('pointermove',  midH.move);
        canvas.removeEventListener('pointerup',    midH.up);
        canvas.removeEventListener('pointerleave', midH.leave);
    }
    delete middleZoomHandlers[canvasId];

    // Clean up flipped triangle materials
    if (flippedTriangleMaterials[canvasId]) {
        Object.entries(flippedTriangleMaterials[canvasId]).forEach(([meshId, data]) => {
            if (data.material) data.material.dispose();
            if (data.observer && scenes[canvasId]) scenes[canvasId].onBeforeRenderObservable.remove(data.observer);
        });
        delete flippedTriangleMaterials[canvasId];
    }

    // Clean up measure tool
    const measureState = measureStates[canvasId];
    if (measureState) {
        if (measureState.observer && scenes[canvasId]) {
            scenes[canvasId].onPointerObservable.remove(measureState.observer);
        }
        if (measureState.labelObserver && scenes[canvasId]) {
            scenes[canvasId].onBeforeRenderObservable.remove(measureState.labelObserver);
        }
        measureState.lines.forEach(mesh => { try { mesh.dispose(); } catch (_) {} });
        measureState.labels.forEach(({ div }) => { try { div.remove(); } catch (_) {} });
        delete measureStates[canvasId];
    }

    // Clean up thickness analysis
    const thicknessState = thicknessStates[canvasId];
    if (thicknessState) {
        if (thicknessState.observer && scenes[canvasId]) {
            scenes[canvasId].onPointerObservable.remove(thicknessState.observer);
        }
        if (thicknessState.line) { try { thicknessState.line.dispose(); } catch (_) {} }
        if (thicknessState.sphere) { try { thicknessState.sphere.dispose(); } catch (_) {} }
        if (thicknessState.label) { try { thicknessState.label.remove(); } catch (_) {} }
        delete thicknessStates[canvasId];
    }

    if (orthoZoomObservers[canvasId]) {
        const cam = mainCameras[canvasId];
        if (cam) cam.onViewMatrixChangedObservable.remove(orthoZoomObservers[canvasId]);
        delete orthoZoomObservers[canvasId];
    }
    _detachEdgeZoomObserver(canvasId);

    clearBoundingBox(canvasId);

    // Clean up body map
    if (perCanvasBodyMap[canvasId]) {
        perCanvasBodyMap[canvasId].forEach(bodyData => {
            if (bodyData.colorMaterial) {
                try { bodyData.colorMaterial.dispose(); } catch (_) {}
            }
        });
        delete perCanvasBodyMap[canvasId];
    }

    // Clean up shadow generator
    if (shadowGenerators[canvasId]) {
        try { shadowGenerators[canvasId].dispose(); } catch (_) {}
        delete shadowGenerators[canvasId];
    }

    disposeSectionVisuals(canvasId, scenes[canvasId]);

    scenes[canvasId]?.dispose();
    engine?.dispose();

    delete engines[canvasId];
    delete scenes[canvasId];
    delete mainCameras[canvasId];
    delete darkModes[canvasId];
    delete modelLoadState[canvasId];
    delete originalMaterials[canvasId];
    delete sceneBoundingBoxes[canvasId];
    delete meshCenters[canvasId];
    delete cameraProjection[canvasId];
    delete edgesEnabled[canvasId];
    delete fitRadiusMap[canvasId];
    delete animStates[canvasId];
    delete autoSpeedCurrent[canvasId];
    delete autoSpeedTarget[canvasId];
    delete analysisModelMeshIds[canvasId];
    delete analysisCameraButtons[canvasId];
    delete localAdvisoryRuns[canvasId];
    terminateLocalAdvisoryWorker(canvasId);
    clearLocalAdvisoryPanel(canvasId);

    // Clean up all per-part overlay slots for this canvas.
    const prefix = `${canvasId}::`;
    [overlayMeshes, overlayLoading, overlayIntendedVisible].forEach(obj => {
        Object.keys(obj).forEach(k => {
            if (k === canvasId || k.startsWith(prefix)) {
                if (obj === overlayMeshes && obj[k] instanceof Map) {
                    obj[k].forEach(meshes => meshes.forEach(m => m.dispose()));
                }
                delete obj[k];
            }
        });
    });
    delete modelScaleFactors[canvasId];
    delete modelCenterOffsets[canvasId];

    delete sectionEdgeMeshes[canvasId];
    delete sectionHatchMeshes[canvasId];
    delete sectionFillMeshes[canvasId];
    delete sectionGhostMeshes[canvasId];
    delete sectionObservers[canvasId];
    delete sectionClipPlanes[canvasId];
    delete _sectionRebuildPending[canvasId];
}

// ── Multi-body support ─────────────────────────────────────────────────────────

/**
 * Assigns distinct colors to each body in a multi-body GLB assembly.
 * @param {string} canvasId
 * @param {Array} bodies - Array of body metadata from SignalR [{ index, name, volumeCm3, colorHex }]
 */
export function setBodies(canvasId, bodies) {
    const scene = scenes[canvasId];
    if (!scene) return;

    const bodyMap = perCanvasBodyMap[canvasId];
    if (!bodyMap) {
        console.warn(`[BabylonViewer] No body map found for canvas ${canvasId}`);
        return;
    }

    // Color palette for bodies (distinct colors for easy visual separation)
    // Colors cycle using modulo for assemblies with >20 bodies
    const palette = CONFIG.MULTI_BODY_PALETTE.map(c => toColor3(c));

    bodies.forEach((body, idx) => {
        if (idx >= bodyMap.size) {
            console.warn(`[BabylonViewer] Body index ${idx} out of range (only ${bodyMap.size} bodies)`);
            return;
        }

        const bodyData = bodyMap.get(idx);
        if (!bodyData) {
            console.warn(`[BabylonViewer] No body data found for index ${idx}`);
            return;
        }

        const color = palette[idx % palette.length];
        const colorMaterial = new BABYLON.PBRMaterial(`body_${idx}_mat`, scene);
        colorMaterial.albedoColor = color;
        colorMaterial.metallic = CONFIG.MATERIAL_MULTI_BODY.metallic;
        colorMaterial.roughness = CONFIG.MATERIAL_MULTI_BODY.roughness;
        colorMaterial.alpha = CONFIG.MATERIAL_MULTI_BODY.alpha;
        colorMaterial.backFaceCulling = false;

        // Share the same material instance across all meshes in this body (no clones).
        // This lets selectBody and clearBodySelection restore color by re-assigning bodyData.colorMaterial.
        bodyData.meshes.forEach(mesh => {
            mesh.material = colorMaterial;
        });

        bodyData.colorMaterial = colorMaterial;
        bodyData.index = idx;
        bodyData.name = body.name;

        debugLog(`[BabylonViewer] Set body ${idx} (${body.name}) to color RGB(${color.r},${color.g},${color.b})`);
    });
}

/**
 * Highlights a single body and dims all other bodies to x-ray mode.
 * @param {string} canvasId
 * @param {number|null} bodyIndex - Index of body to highlight (0-based), or null to clear selection
 */
export function selectBody(canvasId, bodyIndex) {
    const scene = scenes[canvasId];
    if (!scene) return;

    const bodyMap = perCanvasBodyMap[canvasId];
    if (!bodyMap || bodyMap.size === 0) {
        console.warn(`[BabylonViewer] No body map found for canvas ${canvasId}`);
        return;
    }

    // Deselecting: restore all bodies to colored state
    if (bodyIndex === null) {
        clearBodySelection(canvasId);
        return;
    }

    // Check if clicking the same body that's already selected → deselect all
    const currentlySelected = selectedBodyIndices[canvasId];
    if (bodyIndex === currentlySelected) {
        debugLog(`[BabylonViewer] Deselecting body ${bodyIndex} (same body clicked)`);
        clearBodySelection(canvasId);
        selectedBodyIndices[canvasId] = null;
        return;
    }

    // Selecting a different body: highlight one body, make others transparent
    selectedBodyIndices[canvasId] = bodyIndex;
    const xrayMaterial = getOrCreateBodySelectionXrayMaterial(scene);

    // Remove existing highlight layer
    const existingHighlight = scene.getHighlightLayerByName('sel');
    if (existingHighlight) existingHighlight.dispose();

    bodyMap.forEach((bodyData, idx) => {
        const isSelected = (idx === bodyIndex);

        bodyData.meshes.forEach(mesh => {
            if (isSelected) {
                // Fade from transparent (if currently x-ray) to opaque
                const currentAlpha = mesh.material?.alpha || 1.0;
                mesh.material = bodyData.colorMaterial;
                // Animate from current alpha to full opacity
                if (currentAlpha < 1.0) {
                    animateMaterialAlpha(mesh.material, currentAlpha, 1.0, scene, 200);
                }
                mesh.renderOutline = false;
                mesh.outlineWidth = 0;
            } else {
                // Apply x-ray material and animate to transparent ONLY if not already transparent
                // This prevents the "solid → transparent → solid" flicker when switching between bodies
                const currentAlpha = mesh.material?.alpha || 1.0;
                mesh.material = xrayMaterial;
                if (currentAlpha > 0.2) {  // Only animate if currently opaque or semi-opaque (>20%)
                    animateMaterialAlpha(mesh.material, currentAlpha, 0.15, scene, 200);
                } else {
                    // Already transparent — just set the target alpha directly, no animation
                    mesh.material.alpha = 0.15;
                }
                mesh.renderOutline = false;
            }
        });
    });

    debugLog(`[BabylonViewer] Selected body ${bodyIndex}`);
}

/**
 * Enables click-to-select functionality for bodies in the viewer.
 * @param {string} canvasId
 * @param {object} dotNetRef - Blazor component reference for callback
 */
export function enableBodyPicking(canvasId, dotNetRef) {
    const scene = scenes[canvasId];
    if (!scene) return;

    const bodyMap = perCanvasBodyMap[canvasId];
    if (!bodyMap || bodyMap.size === 0) {
        console.warn(`[BabylonViewer] No body map found for canvas ${canvasId} - picking disabled`);
        return;
    }

    // Remove existing pointer observer to avoid duplicates
    if (scene.bodyPickObserver) {
        scene.onPointerObservable.remove(scene.bodyPickObserver);
        delete scene.bodyPickObserver;
    }

    // onPointerObservable is an Observable — must use .add() to register a handler
    scene.bodyPickObserver = scene.onPointerObservable.add((pointerInfo) => {
        if (pointerInfo.type === BABYLON.PointerEventTypes.POINTERDOWN) {
            if (pointerInfo.pickInfo.hit && pointerInfo.pickInfo.pickedMesh) {
                const pickedMesh = pointerInfo.pickInfo.pickedMesh;

                // Walk up the node hierarchy, checking at each level whether the node
                // is one of the body root nodes. This handles any nesting depth.
                let foundIdx = null;
                let node = pickedMesh;
                while (node && foundIdx === null) {
                    bodyMap.forEach((bodyData, idx) => {
                        if (bodyData.rootNode === node) foundIdx = idx;
                    });
                    node = node.parent;
                }

                if (foundIdx !== null) {
                    dotNetRef?.invokeMethodAsync('NotifyBodyPicked', foundIdx);
                    debugLog(`[BabylonViewer] Picked body ${foundIdx}`);
                }
            } else {
                // Clicked empty space - clear selection
                dotNetRef?.invokeMethodAsync('NotifyBodyPicked', null);
                debugLog(`[BabylonViewer] Cleared body selection (clicked empty space)`);
            }
        }
    });

    debugLog(`[BabylonViewer] Body picking enabled for canvas ${canvasId} (${bodyMap.size} bodies)`);
}

/**
 * Clears body selection, restoring all bodies to their colored state.
 */
export function clearBodySelection(canvasId) {
    const scene = scenes[canvasId];
    if (!scene) return;

    const bodyMap = perCanvasBodyMap[canvasId];
    if (!bodyMap || bodyMap.size === 0) return;

    // Restore each body to its shared colored material (no clone needed — same instance for all meshes in a body)
    bodyMap.forEach((bodyData) => {
        if (bodyData.colorMaterial) {
            bodyData.meshes.forEach(mesh => {
                const currentAlpha = mesh.material?.alpha || 0.15;
                mesh.material = bodyData.colorMaterial;
                // Animate from transparent to opaque
                animateMaterialAlpha(mesh.material, currentAlpha, 1.0, scene, 200);
                mesh.renderOutline = false;
                mesh.outlineWidth = 0;
            });
        }
    });

    // Dispose the highlight layer
    const hl = scene.getHighlightLayerByName('sel');
    if (hl) {
        hl.dispose();
    }

    // Reset selected body tracking
    selectedBodyIndices[canvasId] = null;

    debugLog(`[BabylonViewer] Body selection cleared for canvas ${canvasId}`);
}

/**
 * Enables or disables flipped triangle visualization using custom GLSL shaders.
 * Front-facing triangles render in CAD grey, back-facing (flipped) triangles render in red.
 * @param {string} canvasId - Canvas identifier
 * @param {boolean} enabled - true to enable flipped triangle view, false to restore original materials
 */
export function enableFlippedTriangleView(canvasId, enabled) {
    const scene = scenes[canvasId];
    if (!scene) return;

    const tag = '__flipped_overlay__';

    // Always clean up existing overlay meshes first
    scene.meshes.slice().filter(m => m.name.startsWith(tag)).forEach(m => {
        m.material?.dispose();
        m.dispose();
    });
    delete flippedTriangleMaterials[canvasId];

    if (!enabled) {
        debugLog(`[BabylonViewer] Flipped triangle view disabled for canvas ${canvasId}`);
        return;
    }

    // Register simple overlay shaders (discard front faces, paint back faces red)
    if (!BABYLON.Effect.ShadersStore['flippedOverlayVertexShader']) {
        BABYLON.Effect.ShadersStore['flippedOverlayVertexShader'] = `
            precision highp float;
            attribute vec3 position;
            uniform mat4 worldViewProjection;
            void main() { gl_Position = worldViewProjection * vec4(position, 1.0); }
        `;
        BABYLON.Effect.ShadersStore['flippedOverlayFragmentShader'] = `
            precision highp float;
            uniform vec3 flippedColor;
            void main() {
                if (gl_FrontFacing) discard;
                gl_FragColor = vec4(flippedColor, 1.0);
            }
        `;
    }

    const flippedColor = toColor3(CONFIG.FLIPPED_TRIANGLES.flippedColor);
    flippedTriangleMaterials[canvasId] = {};

    scene.meshes.slice().forEach(mesh => {
        if (!mesh.material || isSystemMesh(mesh) || mesh.name === '__root__' || mesh.name.startsWith(tag)) return;

        const overlay = mesh.clone(`${tag}${mesh.uniqueId}`, mesh.parent, true, false);
        if (!overlay) return;
        overlay.isPickable = false;
        overlay.renderingGroupId = mesh.renderingGroupId;
        overlay.alwaysSelectAsActiveMesh = true;

        const sm = new BABYLON.ShaderMaterial(`${tag}mat${mesh.uniqueId}`, scene,
            { vertex: 'flippedOverlay', fragment: 'flippedOverlay' },
            { attributes: ['position'], uniforms: ['worldViewProjection', 'flippedColor'] });
        sm.backFaceCulling = false;
        sm.disableDepthWrite = true;
        sm.setColor3('flippedColor', flippedColor);
        overlay.material = sm;

        flippedTriangleMaterials[canvasId][mesh.uniqueId] = { material: sm, overlay };
    });

    debugLog(`[BabylonViewer] Flipped triangle view enabled for canvas ${canvasId}`);
}

/**
 * Shared picking predicate: true for user-visible model meshes only.
 * Excludes system meshes, __root__, and all analysis-tool helper meshes.
 */
function isMeasurablePredicate(mesh) {
    return mesh
        && isModelMeshForAnalysis(mesh)
        && mesh.isPickable
        && (typeof mesh.isEnabled !== 'function' || mesh.isEnabled())
        && typeof mesh.getTotalVertices === 'function'
        && mesh.getTotalVertices() > 0;
}

/**
 * Picks a point on the mesh at screen coordinates, ensuring ALL faces are tested
 * (front and back facing). Temporarily disables backFaceCulling on model meshes
 * so inside-out or mixed-winding geometry is still pickable.
 */
function pickMeshPoint(scene, x, y, canvasId = null) {
    // Temporarily disable backFaceCulling on all model meshes
    const restore = [];
    scene.meshes.forEach(m => {
        if (isMeasurablePredicate(m) && m.material && m.material.backFaceCulling) {
            restore.push(m);
            m.material.backFaceCulling = false;
        }
    });
    const result = scene.pick(x, y, isMeasurablePredicate);
    // Restore original setting
    restore.forEach(m => { m.material.backFaceCulling = true; });
    return isPickProjectedNearPointer(canvasId, scene, result, x, y) ? result : { hit: false };
}

function withBackFaceCullingDisabled(scene, action) {
    const restore = [];
    scene.meshes.forEach(m => {
        if (isMeasurablePredicate(m) && m.material && m.material.backFaceCulling) {
            restore.push(m);
            m.material.backFaceCulling = false;
        }
    });
    try {
        return action();
    } finally {
        restore.forEach(m => { m.material.backFaceCulling = true; });
    }
}

function vectorFromFeatureValue(value) {
    if (!value) return null;
    if (value instanceof BABYLON.Vector3) return value.clone();
    const x = Number(value.x ?? value.X);
    const y = Number(value.y ?? value.Y);
    const z = Number(value.z ?? value.Z);
    if (!Number.isFinite(x) || !Number.isFinite(y) || !Number.isFinite(z)) return null;
    return new BABYLON.Vector3(x, y, z);
}

function getExplicitRoundFeature(pickResult) {
    const metadata = pickResult?.pickedMesh?.metadata ?? {};
    const candidates = [
        metadata.malievRoundFeature,
        metadata.roundFeature,
        metadata.malievFeature,
        metadata.feature,
    ].filter(Boolean);

    if (Array.isArray(metadata.malievFeatures)) candidates.push(...metadata.malievFeatures);
    if (Array.isArray(metadata.features)) candidates.push(...metadata.features);

    return candidates.find(feature => {
        const type = String(feature.kind ?? feature.type ?? feature.featureType ?? '').toLowerCase();
        return type === 'round' || type === 'cylinder' || type === 'cylindrical' || type === 'bore' || type === 'diameter';
    }) ?? null;
}

function inferRoundFeatureFromPick(pickResult) {
    const mesh = pickResult?.pickedMesh;
    if (!mesh) return null;

    const feature = getExplicitRoundFeature(pickResult);
    if (!feature) return null;

    const center = vectorFromFeatureValue(feature.center ?? feature.anchor ?? feature.axisPoint ?? feature.point)
        ?? pickResult.pickedPoint?.clone();
    const axisVector = vectorFromFeatureValue(feature.axis ?? feature.axisVector ?? feature.normal)
        ?? new BABYLON.Vector3(0, 0, 1);
    const diameter = Number(feature.diameter ?? feature.Diameter);
    const radius = Number(feature.radius ?? feature.Radius);
    const resolvedRadius = Number.isFinite(radius) && radius > 0
        ? radius
        : Number.isFinite(diameter) && diameter > 0
            ? diameter / 2
            : null;

    if (!center || !resolvedRadius) return null;

    return {
        kind: 'round',
        point: pickResult.pickedPoint?.clone() ?? center.clone(),
        anchor: center,
        axis: axisVector,
        radius: resolvedRadius,
        diameter: resolvedRadius * 2,
        label: 'Diameter',
    };
}

function pickCadFeature(scene, x, y, canvasId = null) {
    const pickResult = pickMeshPoint(scene, x, y, canvasId);
    if (!pickResult?.hit || !pickResult.pickedPoint || !pickResult.pickedMesh) return null;

    const normal = pickResult.getNormal(true, false) || new BABYLON.Vector3(0, 0, 1);
    const roundFeature = inferRoundFeatureFromPick(pickResult);
    if (roundFeature) return roundFeature;

    return {
        kind: 'face',
        point: pickResult.pickedPoint.clone(),
        anchor: pickResult.pickedPoint.clone(),
        normal: normal.clone(),
        label: 'Face',
    };
}

function createRoundFeatureHighlight(scene, feature) {
    if (!feature || feature.kind !== 'round') return null;

    const axis = feature.axis.clone().normalize();
    const helper = Math.abs(axis.z) < 0.9 ? new BABYLON.Vector3(0, 0, 1) : new BABYLON.Vector3(0, 1, 0);
    const u = BABYLON.Vector3.Cross(axis, helper).normalize();
    const v = BABYLON.Vector3.Cross(axis, u).normalize();
    const points = [];
    const segments = 96;
    for (let i = 0; i <= segments; i += 1) {
        const a = (Math.PI * 2 * i) / segments;
        points.push(feature.anchor
            .add(u.scale(Math.cos(a) * feature.radius))
            .add(v.scale(Math.sin(a) * feature.radius)));
    }

    const line = BABYLON.MeshBuilder.CreateLines('measure_round_highlight', { points }, scene);
    line.color = new BABYLON.Color3(1, 0.22, 0.68);
    return markAnalysisHelperMesh(line);
}

function pickOppositeThicknessHit(scene, entryPoint, normal, entryMesh, entryFaceId) {
    if (!normal) return null;

    return withBackFaceCullingDisabled(scene, () => {
        const candidates = [];
        for (const dir of [normal.scale(-1), normal]) {
            if (dir.length() < 1e-6) continue;
            dir.normalize();
            const ray = new BABYLON.Ray(
                entryPoint.add(dir.scale(0.15)),
                dir,
                CONFIG.THICKNESS.maxRayDistance
            );
            const hits = scene.multiPickWithRay
                ? (scene.multiPickWithRay(ray, isMeasurablePredicate) || [])
                : [scene.pickWithRay(ray, isMeasurablePredicate)].filter(Boolean);

            hits.forEach(hit => {
                if (!hit?.hit || !hit.pickedPoint) return;
                const distance = BABYLON.Vector3.Distance(entryPoint, hit.pickedPoint);
                if (distance < 0.25) return;
                if (hit.pickedMesh === entryMesh && hit.faceId === entryFaceId) return;

                let normalScore = 0;
                try {
                    const hitNormal = hit.getNormal(true, false);
                    if (hitNormal) normalScore = -BABYLON.Vector3.Dot(normal.clone().normalize(), hitNormal.normalize());
                } catch (_) {
                    normalScore = 0;
                }
                candidates.push({ hit, distance, normalScore });
            });
        }

        if (candidates.length === 0) return null;
        candidates.sort((a, b) => {
            const aOpposed = a.normalScore > 0.15 ? 0 : 1;
            const bOpposed = b.normalScore > 0.15 ? 0 : 1;
            return aOpposed - bOpposed || a.distance - b.distance;
        });
        return candidates[0].hit;
    });
}

/**
 * Enables the measure tool for point-to-point distance and angle measurement.
 * @param {string} canvasId - Canvas identifier
 * @param {object} dotNetRef - DotNetObjectReference for callbacks
 */
export function enableMeasureTool(canvasId, dotNetRef) {
    const scene = scenes[canvasId];
    if (!scene) return;

    // Disable if already active
    disableMeasureTool(canvasId);

    measureStates[canvasId] = {
        active: true,
        pointA: null,
        pointB: null,
        featureA: null,
        featureB: null,
        normalA: null,
        normalB: null,
        lines: [],
        labels: [],
        observer: null,
        hoverDot: null,
        hoverFeatureHighlight: null,
        cursorDots: [],
        _downX: null,
        _downY: null,
    };

    const state = measureStates[canvasId];
    const canvas = document.getElementById(canvasId);
    if (!canvas) return;

    ensureModelMeshesTagged(canvasId, scene);
    setAnalysisNavigationLock(canvasId, true);
    canvas.style.cursor = 'crosshair';

    function makeUnpickable(mesh) { markAnalysisHelperMesh(mesh); }

    function createHoverDot(point) {
        if (state.hoverDot) { try { state.hoverDot.dispose(); } catch (_) {} }
        if (state.hoverFeatureHighlight) { try { state.hoverFeatureHighlight.dispose(); } catch (_) {} state.hoverFeatureHighlight = null; }
        const dot = BABYLON.MeshBuilder.CreateSphere('measure_hover_dot', { diameter: 0.8 }, scene);
        dot.position = point.clone();
        const mat = new BABYLON.StandardMaterial('measure_hover_dot_mat', scene);
        mat.diffuseColor = new BABYLON.Color3(1, 0.2, 0.2);
        mat.emissiveColor = new BABYLON.Color3(1, 0.3, 0.3);
        mat.disableLighting = true;
        dot.material = mat;
        makeUnpickable(dot);
        state.hoverDot = dot;
    }

    function showDiameterLabel(feature) {
        if (feature.kind !== 'round') return;
        const labelDiv = document.createElement('div');
        labelDiv.className = 'measure-label';
        labelDiv.style.cssText = `
            position: fixed; transform: translate(-50%, -50%);
            background: rgba(0, 0, 0, 0.85); color: #ff4fb3;
            padding: 6px 10px; border-radius: 4px;
            font-family: 'Segoe UI', sans-serif; font-size: 13px; font-weight: 600;
            pointer-events: none; white-space: nowrap; z-index: 1000;
            border: 1px solid #ff4fb3;
        `;
        labelDiv.innerHTML = `Ø ${feature.diameter.toFixed(2)} mm`;
        document.body.appendChild(labelDiv);
        state.labels.push({ div: labelDiv, worldPos: feature.anchor.clone() });
    }

    function createCursorDot(point) {
        const dot = BABYLON.MeshBuilder.CreateSphere('measure_cursor_dot', { diameter: 0.6 }, scene);
        dot.position = point.clone();
        const mat = new BABYLON.StandardMaterial('measure_cursor_dot_mat', scene);
        mat.diffuseColor = new BABYLON.Color3(1, 0, 0);
        mat.emissiveColor = new BABYLON.Color3(1, 0, 0);
        mat.disableLighting = true;
        dot.material = mat;
        makeUnpickable(dot);
        state.cursorDots.push(dot);
    }

    function clearMeasureHelpers() {
        state.lines.forEach(m => { try { m.dispose(); } catch (_) {} });
        state.labels.forEach(({ div }) => { try { div.remove(); } catch (_) {} });
        state.cursorDots.forEach(m => { try { m.dispose(); } catch (_) {} });
        state.lines = [];
        state.labels = [];
        state.cursorDots = [];
    }

    state.observer = scene.onPointerObservable.add((pointerInfo) => {
        if (!measureStates[canvasId]?.active) return;
        const coords = getPointerInfoRenderCoordinates(canvasId, scene, pointerInfo);

        switch (pointerInfo.type) {
            case BABYLON.PointerEventTypes.POINTERDOWN: {
                if (!coords) break;
                state._downX = coords.x;
                state._downY = coords.y;
                break;
            }

            case BABYLON.PointerEventTypes.POINTERUP: {
                if (!coords) break;
                // Only count as a click if pointer didn't move much (< 5px = camera drag)
                const dx = coords.x - (state._downX ?? coords.x);
                const dy = coords.y - (state._downY ?? coords.y);
                if (dx * dx + dy * dy > 25) { state._downX = null; state._downY = null; break; }
                state._downX = null; state._downY = null;

                const pickResult = pickMeshPoint(scene, coords.x, coords.y, canvasId);
                const feature = pickCadFeature(scene, coords.x, coords.y, canvasId);
                if (!pickResult?.hit || !pickResult.pickedMesh || !feature) return;

                const pickedPoint = feature.anchor ?? pickResult.pickedPoint;
                const normal = feature.normal ?? pickResult.getNormal(true) ?? feature.axis;

                if (!state.pointA) {
                    state.pointA = pickedPoint.clone();
                    state.featureA = feature;
                    state.normalA = normal?.clone() || new BABYLON.Vector3(0, 0, 1);

                    const markerA = BABYLON.MeshBuilder.CreateSphere('measure_A', { diameter: CONFIG.MEASURE.endpointSize }, scene);
                    markerA.position = state.pointA.clone();
                    const matA = new BABYLON.StandardMaterial('measure_A_mat', scene);
                    matA.diffuseColor = toColor3(CONFIG.MEASURE.lineColor);
                    matA.emissiveColor = toColor3(CONFIG.MEASURE.lineColor);
                    markerA.material = matA;
                    makeUnpickable(markerA);
                    state.lines.push(markerA);
                    createCursorDot(pickedPoint);
                    const roundHighlight = createRoundFeatureHighlight(scene, feature);
                    if (roundHighlight) state.lines.push(roundHighlight);
                    showDiameterLabel(feature);

                } else if (!state.pointB) {
                    state.pointB = pickedPoint.clone();
                    state.featureB = feature;
                    state.normalB = normal?.clone() || new BABYLON.Vector3(0, 0, 1);

                    const markerB = BABYLON.MeshBuilder.CreateSphere('measure_B', { diameter: CONFIG.MEASURE.endpointSize }, scene);
                    markerB.position = state.pointB.clone();
                    const matB = new BABYLON.StandardMaterial('measure_B_mat', scene);
                    matB.diffuseColor = toColor3(CONFIG.MEASURE.lineColor);
                    matB.emissiveColor = toColor3(CONFIG.MEASURE.lineColor);
                    markerB.material = matB;
                    makeUnpickable(markerB);
                    state.lines.push(markerB);

                    const line = BABYLON.MeshBuilder.CreateLines('measure_line', {
                        points: [state.pointA, state.pointB]
                    }, scene);
                    line.color = toColor3(CONFIG.MEASURE.lineColor);
                    makeUnpickable(line);
                    state.lines.push(line);

                    const direction = state.pointB.subtract(state.pointA).normalize();
                    const arrowSize = 0.8;

                    const coneA = BABYLON.MeshBuilder.CreateCylinder('measure_arrowA', {
                        diameterTop: 0, diameterBottom: arrowSize, height: arrowSize * 1.5, tessellation: 12
                    }, scene);
                    coneA.position = state.pointA.add(direction.scale(arrowSize * 0.75));
                    coneA.rotationQuaternion = BABYLON.Quaternion.RotationAxis(
                        BABYLON.Vector3.Cross(new BABYLON.Vector3(0, 1, 0), direction),
                        Math.acos(Math.max(-1, Math.min(1, BABYLON.Vector3.Dot(new BABYLON.Vector3(0, 1, 0), direction))))
                    );
                    const matArrowA = new BABYLON.StandardMaterial('measure_arrowA_mat', scene);
                    matArrowA.diffuseColor = toColor3(CONFIG.MEASURE.lineColor);
                    matArrowA.emissiveColor = toColor3(CONFIG.MEASURE.lineColor);
                    coneA.material = matArrowA;
                    makeUnpickable(coneA);
                    state.lines.push(coneA);

                    const coneB = BABYLON.MeshBuilder.CreateCylinder('measure_arrowB', {
                        diameterTop: 0, diameterBottom: arrowSize, height: arrowSize * 1.5, tessellation: 12
                    }, scene);
                    coneB.position = state.pointB.subtract(direction.scale(arrowSize * 0.75));
                    coneB.rotationQuaternion = BABYLON.Quaternion.RotationAxis(
                        BABYLON.Vector3.Cross(new BABYLON.Vector3(0, 1, 0), direction.scale(-1).normalize()),
                        Math.acos(Math.max(-1, Math.min(1, BABYLON.Vector3.Dot(new BABYLON.Vector3(0, 1, 0), direction.scale(-1)))))
                    );
                    const matArrowB = new BABYLON.StandardMaterial('measure_arrowB_mat', scene);
                    matArrowB.diffuseColor = toColor3(CONFIG.MEASURE.lineColor);
                    matArrowB.emissiveColor = toColor3(CONFIG.MEASURE.lineColor);
                    coneB.material = matArrowB;
                    makeUnpickable(coneB);
                    state.lines.push(coneB);

                    const distance = BABYLON.Vector3.Distance(state.pointA, state.pointB);
                    const dot = BABYLON.Vector3.Dot(state.normalA.normalize(), state.normalB.normalize());
                    const angleRad = Math.acos(Math.max(-1, Math.min(1, dot)));
                    const angleDeg = angleRad * (180 / Math.PI);

                    const midPoint = BABYLON.Vector3.Center(state.pointA, state.pointB);
                    const labelDiv = document.createElement('div');
                    labelDiv.className = 'measure-label';
                    labelDiv.style.cssText = `
                        position: fixed; transform: translate(-50%, -50%);
                        background: rgba(0, 0, 0, 0.85); color: #ffd700;
                        padding: 6px 10px; border-radius: 4px;
                        font-family: 'Segoe UI', sans-serif; font-size: 13px; font-weight: 600;
                        pointer-events: none; white-space: nowrap; z-index: 1000;
                        border: 1px solid #ffd700;
                    `;
                    const diameterNotes = [state.featureA, state.featureB]
                        .filter(f => f?.kind === 'round')
                        .map(f => `Ø ${f.diameter.toFixed(2)} mm`);
                    const diameterHtml = diameterNotes.length > 0
                        ? `<br><span style="font-size: 11px; opacity: 0.9;">${diameterNotes.join(' · ')}</span>`
                        : '';
                    labelDiv.innerHTML = `${distance.toFixed(2)} mm${diameterHtml}<br><span style="font-size: 11px; opacity: 0.8;">∠ ${angleDeg.toFixed(1)}°</span>`;
                    document.body.appendChild(labelDiv);
                    state.labels.push({ div: labelDiv, worldPos: midPoint });

                    createCursorDot(pickedPoint);

                    if (dotNetRef) {
                        try { dotNetRef.invokeMethodAsync('NotifyMeasureResult', distance.toFixed(2), angleDeg.toFixed(1)); }
                        catch (e) { console.warn('[BabylonViewer] Failed to notify measure result:', e); }
                    }
                } else {
                    clearMeasureHelpers();
                    state.pointA = pickedPoint.clone();
                    state.pointB = null;
                    state.featureA = feature;
                    state.featureB = null;
                    state.normalA = normal?.clone() || new BABYLON.Vector3(0, 0, 1);
                    state.normalB = null;

                    const markerA = BABYLON.MeshBuilder.CreateSphere('measure_A', { diameter: CONFIG.MEASURE.endpointSize }, scene);
                    markerA.position = state.pointA.clone();
                    const matA = new BABYLON.StandardMaterial('measure_A_mat', scene);
                    matA.diffuseColor = toColor3(CONFIG.MEASURE.lineColor);
                    matA.emissiveColor = toColor3(CONFIG.MEASURE.lineColor);
                    markerA.material = matA;
                    makeUnpickable(markerA);
                    state.lines.push(markerA);
                    createCursorDot(pickedPoint);
                    const roundHighlight = createRoundFeatureHighlight(scene, feature);
                    if (roundHighlight) state.lines.push(roundHighlight);
                    showDiameterLabel(feature);
                }
                break;
            }

            case BABYLON.PointerEventTypes.POINTERMOVE: {
                if (!coords) break;
                const hoverFeature = pickCadFeature(scene, coords.x, coords.y, canvasId);

                // Update hover dot position (face-precise feedback)
                if (hoverFeature) {
                    createHoverDot(hoverFeature.point ?? hoverFeature.anchor);
                    state.hoverFeatureHighlight = createRoundFeatureHighlight(scene, hoverFeature);
                } else if (state.hoverDot) {
                    try { state.hoverDot.dispose(); } catch (_) {}
                    state.hoverDot = null;
                    if (state.hoverFeatureHighlight) { try { state.hoverFeatureHighlight.dispose(); } catch (_) {} state.hoverFeatureHighlight = null; }
                }

                // Preview line from A to cursor (only while waiting for second click)
                if (state.pointA && !state.pointB && hoverFeature) {
                    const prevPreview = state.lines.find(l => l.name === 'measure_preview');
                    if (prevPreview) {
                        prevPreview.dispose();
                        state.lines = state.lines.filter(l => l !== prevPreview);
                    }

                    const previewLine = BABYLON.MeshBuilder.CreateLines('measure_preview', {
                        points: [state.pointA, hoverFeature.anchor],
                        updatable: true
                    }, scene);
                    previewLine.color = toColor3({ r: 1.0, g: 0.85, b: 0.0, a: 0.5 });
                    previewLine.alpha = 0.5;
                    makeUnpickable(previewLine);
                    state.lines.push(previewLine);
                }
                break;
            }
        }
    });

    const labelUpdateObserver = scene.onBeforeRenderObservable.add(() => {
        state.labels.forEach(({ div, worldPos }) => {
            updateLabelPosition(div, worldPos, canvasId);
        });
    });
    state.labelObserver = labelUpdateObserver;

    debugLog(`[BabylonViewer] Measure tool enabled for canvas ${canvasId}`);
}

/**
 * Disables the measure tool and cleans up resources.
 * @param {string} canvasId - Canvas identifier
 */
export function disableMeasureTool(canvasId) {
    const state = measureStates[canvasId];
    if (!state) return;

    const scene = scenes[canvasId];
    const canvas = document.getElementById(canvasId);

    // Remove observers
    if (state.observer && scene) {
        scene.onPointerObservable.remove(state.observer);
    }
    if (state.labelObserver && scene) {
        scene.onBeforeRenderObservable.remove(state.labelObserver);
    }

    // Dispose hover dot and cursor dots
    if (state.hoverDot) { try { state.hoverDot.dispose(); } catch (_) {} }
    if (state.hoverFeatureHighlight) { try { state.hoverFeatureHighlight.dispose(); } catch (_) {} }
    state.cursorDots?.forEach(mesh => { try { mesh.dispose(); } catch (_) {} });

    // Dispose lines and meshes
    state.lines.forEach(mesh => { try { mesh.dispose(); } catch (_) {} });

    // Remove labels
    state.labels.forEach(({ div }) => { try { div.remove(); } catch (_) {} });

    // Reset cursor
    if (canvas) canvas.style.cursor = 'default';

    delete measureStates[canvasId];
    setAnalysisNavigationLock(canvasId, false);
    debugLog(`[BabylonViewer] Measure tool disabled for canvas ${canvasId}`);
}

