/**
 * Returns a dedicated xray material for the section-view ghost (hidden half).
 * Separate from the toolbar xray so alpha and clip plane can differ independently.
 * @param {BABYLON.Scene} scene
 * @returns {BABYLON.StandardMaterial}
 */
function _getOrCreateSectionGhostMaterial(scene) {
    const name = '__section_ghost__';
    const existing = scene.getMaterialByName(name);
    if (existing) return existing;

    const mat = new BABYLON.StandardMaterial(name, scene);
    mat.diffuseColor     = new BABYLON.Color3(0.55, 0.62, 0.72);
    mat.emissiveColor    = new BABYLON.Color3(0.05, 0.07, 0.12);
    mat.alpha            = 0.08;
    mat.backFaceCulling  = false;
    mat.twoSidedLighting = true;
    return mat;
}

/**
 * Creates ghost (xray) clones of every visible body mesh with the clip plane inverted,
 * so the hidden half appears as a faint see-through silhouette.
 * @param {string}  canvasId
 * @param {BABYLON.Scene} scene
 * @param {number}  nx  plane normal x
 * @param {number}  ny  plane normal y
 * @param {number}  nz  plane normal z
 * @param {number}  d   plane constant
 */
function _createSectionGhosts(canvasId, scene, nx, ny, nz, d) {
    _disposeSectionGhosts(canvasId);

    const ghostMat = _getOrCreateSectionGhostMaterial(scene);
    // Each ghost material instance needs its own clipPlane, so clone per call
    // (but we reuse the same ghost mat with a per-mesh override via material.clipPlane)
    const invertedPlane = new BABYLON.Plane(-nx, -ny, -nz, -d);

    const ghosts = [];
    for (const mesh of scene.meshes) {
        if (!mesh.isVisible || !isModelMeshForAnalysis(mesh, canvasId)) continue;
        if (typeof mesh.clone !== 'function') continue;

        const clone = mesh.clone(`__section_ghost_${mesh.uniqueId}`, null, false);
        if (!clone) continue;

        // Create a per-clone material so clipPlane is independent of the shared mat
        const cloneMat = ghostMat.clone(`__section_ghost_mat_${mesh.uniqueId}`);
        cloneMat.clipPlane = invertedPlane;
        clone.material = cloneMat;
        clone.receiveShadows = false;
        markAnalysisHelperMesh(clone);
        ghosts.push(clone);
    }
    sectionGhostMeshes[canvasId] = ghosts;
}

/**
 * Disposes all section ghost meshes (and their per-clone materials) for a canvas.
 * @param {string} canvasId
 */
function _disposeSectionGhosts(canvasId) {
    const ghosts = sectionGhostMeshes[canvasId];
    if (!ghosts) return;
    for (const g of ghosts) {
        if (g.material) g.material.dispose();
        g.dispose();
    }
    sectionGhostMeshes[canvasId] = null;
}

function isAnalysisHelperMesh(mesh) {
    const name = mesh?.name ?? '';
    return !!mesh?.metadata?.malievAnalysisHelper
        || name === '__grid__'
        || name === '__shadow_catcher__'
        || name === '__root__'
        || name.startsWith('__axis')
        || name.startsWith('bbox_')
        || name.startsWith('__section_ghost')
        || name.startsWith('__section_edges_')
        || name.startsWith('__section_hatch_')
        || name.startsWith('__flipped_overlay__')
        || name.startsWith('measure_')
        || name.startsWith('thickness_');
}

function markAnalysisHelperMesh(mesh) {
    if (!mesh) return mesh;
    mesh.metadata = { ...(mesh.metadata ?? {}), malievAnalysisHelper: true, malievModelMesh: false };
    mesh.isPickable = false;
    return mesh;
}

function isOverlayMeshForCanvas(canvasId, mesh) {
    if (!mesh) return false;
    const direct = overlayMeshes[canvasId];
    if (direct instanceof Map) {
        for (const [, meshes] of direct) {
            if (meshes?.some(m => m === mesh || m?.uniqueId === mesh.uniqueId)) return true;
        }
    }

    const prefix = `${canvasId}::`;
    for (const [key, value] of Object.entries(overlayMeshes)) {
        if (!key.startsWith(prefix) || !(value instanceof Map)) continue;
        for (const [, meshes] of value) {
            if (meshes?.some(m => m === mesh || m?.uniqueId === mesh.uniqueId)) return true;
        }
    }

    return false;
}

function isModelMeshCandidate(mesh, canvasId) {
    return !!mesh
        && !isAnalysisHelperMesh(mesh)
        && !isOverlayMeshForCanvas(canvasId, mesh)
        && typeof mesh.getTotalVertices === 'function'
        && mesh.getTotalVertices() > 0
        && (typeof mesh.isEnabled !== 'function' || mesh.isEnabled());
}

function tagModelMeshesForAnalysis(canvasId, scene = scenes[canvasId]) {
    if (!scene) return;

    const ids = new Set();
    scene.meshes.forEach(mesh => {
        if (isModelMeshCandidate(mesh, canvasId)) {
            mesh.metadata = { ...(mesh.metadata ?? {}), malievModelMesh: true, malievAnalysisHelper: false };
            mesh.isPickable = true;
            ids.add(mesh.uniqueId);
        } else if (isAnalysisHelperMesh(mesh) || isOverlayMeshForCanvas(canvasId, mesh)) {
            if (mesh.metadata?.malievModelMesh) {
                mesh.metadata = { ...mesh.metadata, malievModelMesh: false };
            }
            if (isAnalysisHelperMesh(mesh)) mesh.isPickable = false;
        }
    });
    analysisModelMeshIds[canvasId] = ids;
}

function ensureModelMeshesTagged(canvasId, scene = scenes[canvasId]) {
    if (!analysisModelMeshIds[canvasId] || analysisModelMeshIds[canvasId].size === 0) {
        tagModelMeshesForAnalysis(canvasId, scene);
    }
}

function isModelMeshForAnalysis(mesh, canvasId = null) {
    if (!mesh || isAnalysisHelperMesh(mesh)) return false;
    if (canvasId && analysisModelMeshIds[canvasId]?.has(mesh.uniqueId)) return true;
    return mesh.metadata?.malievModelMesh === true;
}

/**
 * Checks if a mesh is a system mesh (grid, axis gizmo, bounding box, analysis helpers) that should be skipped.
 * @param {BABYLON.AbstractMesh} mesh
 * @returns {boolean}
 */
function isSystemMesh(mesh) {
    return isAnalysisHelperMesh(mesh);
}

function toPlainNumberArray(values) {
    return Array.from(values ?? [], value => Number(value)).filter(Number.isFinite);
}

function getMeshWorldPositions(mesh, positions) {
    if (!mesh || !positions || positions.length === 0) return [];

    try {
        mesh.computeWorldMatrix?.(true);
        const matrix = mesh.getWorldMatrix?.();
        if (!matrix || !BABYLON?.Vector3?.TransformCoordinates) {
            return toPlainNumberArray(positions);
        }

        const transformed = [];
        for (let index = 0; index < positions.length; index += 3) {
            const point = BABYLON.Vector3.TransformCoordinates(
                new BABYLON.Vector3(
                    Number(positions[index]),
                    Number(positions[index + 1]),
                    Number(positions[index + 2])
                ),
                matrix
            );
            transformed.push(point.x, point.y, point.z);
        }
        return transformed;
    } catch (_) {
        return toPlainNumberArray(positions);
    }
}

/**
 * Collects mesh buffers for the browser advisory geometry runtime.
 * @param {string} canvasId
 * @returns {Array<{positions:number[], indices:number[]}>}
 */
export function collectAdvisoryMeshBuffers(canvasId) {
    const scene = scenes[canvasId];
    if (!scene) return [];

    ensureModelMeshesTagged(canvasId, scene);
    const buffers = [];
    for (const mesh of scene.meshes ?? []) {
        if (!mesh?.isVisible || !isModelMeshForAnalysis(mesh, canvasId)) continue;
        const positions = mesh.getVerticesData?.(BABYLON.VertexBuffer.PositionKind);
        if (!positions || positions.length < 9) continue;

        const indices = mesh.getIndices?.() ?? [];
        const safeIndices = indices.length > 0
            ? toPlainNumberArray(indices)
            : Array.from({ length: positions.length / 3 }, (_, index) => index);
        if (safeIndices.length < 3) continue;

        buffers.push({
            positions: getMeshWorldPositions(mesh, positions),
            indices: safeIndices,
        });
    }

    return buffers;
}

function resolveRuntimeAssetUrl(assetPath, assetBaseUrl = LOCAL_ADVISORY_ASSET_BASE_URL) {
    const value = String(assetPath ?? '');
    if (value.includes('..') || value.includes('\\')) return null;
    const name = value.split('?')[0].split('/').pop();
    if (!name || name.includes('..') || name.includes('/') || name.includes('\\')) return null;
    return `${assetBaseUrl}${encodeURIComponent(name)}`;
}

async function fetchLocalAdvisoryManifest(manifestUrl) {
    let lastResponse = null;
    for (let attempt = 0; attempt < 2; attempt += 1) {
        try {
            lastResponse = await fetch(manifestUrl, {
                cache: 'no-cache',
                credentials: 'same-origin',
            });
        } catch (_) {
            lastResponse = null;
        }

        if (lastResponse?.ok || (lastResponse && Number(lastResponse.status) < 500)) return lastResponse;
        await Promise.resolve();
    }

    return lastResponse;
}

