/**
 * Positions the camera using a world-space direction vector rather than alpha/beta
 * so that the Z-up coordinate system is respected without spherical-coord confusion.
 * @param {boolean} smooth - If true, animates the transition smoothly
 */
function applyPreset(cam, presetName, smooth = false, canvasId = null) {
    const p = PRESETS[presetName];
    if (!p) return;

    const targetUp = new BABYLON.Vector3(p.up[0], p.up[1], p.up[2]);
    const t = cam.target;

    // Each preset defines a zoom factor (1.0 = fit-to-view). Resolve to a radius.
    const initialRadius = canvasId ? (fitRadiusMap[canvasId] || cam.radius) : cam.radius;
    const targetRadius = initialRadius * (p.zoom || 1.0);
    const currentRadius = cam.radius;

    const targetPos = new BABYLON.Vector3(
        t.x + p.dir[0] * targetRadius,
        t.y + p.dir[1] * targetRadius,
        t.z + p.dir[2] * targetRadius
    );

    if (smooth && canvasId) {
        const scene = scenes[canvasId];
        if (scene) {
            // Quaternion arc (direction + zoom) and up-vector transition in parallel
            Promise.all([
                animateCameraUpVector(cam, p.up, scene),
                animateCameraArc(cam, p.dir, currentRadius, targetRadius, canvasId)
            ]).then(() => {
                // Snap to exact final state
                cam.upVector = targetUp;
                cam.setPosition(targetPos);
                if (cameraProjection[canvasId] === 'orthographic') {
                    orthoZoomFactors[canvasId] = p.zoom || 1.0;
                    const engine = engines[canvasId];
                    if (engine) {
                        const h = initialRadius * (p.zoom || 1.0) * ORTHO_RADIUS_FACTOR;
                        const asp = engine.getAspectRatio(cam);
                        cam.orthoLeft   = -h * asp;
                        cam.orthoRight  =  h * asp;
                        cam.orthoTop    =  h;
                        cam.orthoBottom = -h;
                    }
                    cam.radius = initialRadius;
                } else {
                    cam.radius = targetRadius;
                }
            });
            return;
        }
    }

    // Immediate mode
    cam.upVector = targetUp;
    cam.setPosition(targetPos);
    if (canvasId && cameraProjection[canvasId] === 'orthographic') {
        orthoZoomFactors[canvasId] = p.zoom || 1.0;
        const engine = engines[canvasId];
        if (engine) {
            const h = initialRadius * (p.zoom || 1.0) * ORTHO_RADIUS_FACTOR;
            const asp = engine.getAspectRatio(cam);
            cam.orthoLeft   = -h * asp;
            cam.orthoRight  =  h * asp;
            cam.orthoTop    =  h;
            cam.orthoBottom = -h;
        }
        cam.radius = initialRadius;
    } else {
        cam.radius = targetRadius;
    }
}

// ── initialize ────────────────────────────────────────────────────────────────

/**
 * @param {string}  canvasId
 * @param {string}  fileUrl        Signed URL to the 3D file
 * @param {string}  fileExt        e.g. ".glb"
 * @param {boolean} isDark
 * @param {object|null} knownDimsMm  Optional { x, y, z } bounding box in mm from server
 * @param {object|null} dotNetRef   Optional DotNetObjectReference for error callbacks
 * @param {object|null} viewerSettings  Per-part render/projection/section settings
 */
export async function initialize(canvasId, fileUrl, fileExt, isDark, knownDimsMm, dotNetRef, viewerSettings = {}) {
    viewerSettings = normalizeViewerSettings(viewerSettings);
    // Debug logging: track when initialize is called
    const sanitizedUrl = fileUrl ? (fileUrl.includes('?') ? fileUrl.substring(0, fileUrl.indexOf('?')) + '?[SIGNED_URL]' : fileUrl) : '(none)';
    debugLog('[BabylonViewer] initialize START:', { canvasId, url: sanitizedUrl, fileExt, prevGen: loadGenerations[canvasId] || 0, timestamp: Date.now() });

    try {
        await loadScript('./lib/babylonjs/babylon.js');
        configureBabylonLogger();
        await loadScript('./lib/babylonjs/babylonjs.loaders.min.js');
        await loadScript('./lib/babylonjs/babylonjs.materials.min.js');

        const canvas = document.getElementById(canvasId);
        if (!canvas) { console.error(`[BabylonViewer] Canvas #${canvasId} not found.`); return; }

        canvas.style.background = 'transparent';
        canvas.style.opacity = '0';
        canvas.style.transition = `opacity ${CONFIG.ANIMATION_CANVAS_FADE_IN} ease-in`;

        if (engines[canvasId]) await dispose(canvasId);

        // Generation counter: any stale retry or async callback from a previous initialize()
        // call will see a mismatched generation and bail out, preventing duplicate mesh appends.
        loadGenerations[canvasId] = (loadGenerations[canvasId] || 0) + 1;
        const currentGen = loadGenerations[canvasId];

        darkModes[canvasId]        = !!isDark;
        modelLoadState[canvasId]   = 'loading';
        originalMaterials[canvasId]= {};
        sceneBoundingBoxes[canvasId] = null;
        meshCenters[canvasId]      = null;
        edgesEnabled[canvasId]     = !!viewerSettings.edgesEnabled;

        const engine = new BABYLON.Engine(canvas, true, {
            premultipliedAlpha: false,
            alpha: true,
            disableUniformBuffers: true,
        });
        const scene  = new BABYLON.Scene(engine);
        engine.resize();

        scene.clearColor = new BABYLON.Color4(0, 0, 0, 0);

        // Camera (upVector updated after model loads)
        const camera = new BABYLON.ArcRotateCamera('cam',
            Math.PI / 4, Math.acos(1 / Math.sqrt(3)) + (15 * Math.PI / 180), 10,
            BABYLON.Vector3.Zero(), scene);
        camera.attachControl(canvas, true);
        camera.wheelPrecision = 5; // Will be tuned by fitCameraToMesh after load
        camera.upVector = new BABYLON.Vector3(0, 0, 1); // Z-up
        // Disable built-in panning — replaced by pick-point pan below
        camera.panningSensibility = 0;
        // Restrict rotation to left-click only — right-click is reserved for pick-point pan
        camera.inputs.attached.pointers.buttons = [0];
        // Remove default pole clamp — allow full vertical rotation over top and bottom
        camera.lowerBetaLimit = null;
        camera.upperBetaLimit = null;
        mainCameras[canvasId] = camera;

        // Set initial projection mode based on parameter
        debugLog('[BabylonViewer] initialize: cameraProjection =', viewerSettings.cameraProjection);
        if (viewerSettings.cameraProjection === 'orthographic') {
            setCameraProjection(canvasId, 'orthographic');
        }

        // ── Right-click pixel-perfect pan (attached now, updated each model load) ────
        attachPickPointPan(canvasId, canvas, camera);

        // Placeholder light (replaced after model loads)
        new BABYLON.HemisphericLight('__init_light__', new BABYLON.Vector3(0, 0, 1), scene);

        const forcedExt = resolveExtension(fileUrl, fileExt);
        BABYLON.SceneLoader.ShowLoadingScreen = false;

        // Attempt to pre-fetch the GLB into a local blob URL. This allows instant
        // re-render on subsequent tab switches to the same part (blob URL never expires).
        let _resolvedUrl = fileUrl;
        if (fileUrl && (fileUrl.endsWith('.glb') || fileUrl.includes('.glb?'))) {
            try {
                _resolvedUrl = await _fetchGlbCached(fileUrl);
            } catch (_fetchErr) {
                console.warn('[BabylonViewer] GLB pre-fetch failed, falling back to direct URL:', _fetchErr.message);
                _resolvedUrl = fileUrl;
            }
        }
        const _effectiveFileUrl = _resolvedUrl;

        // Retry-with-backoff: the GLB may not yet be in GCS when the signed URL arrives
        // (race between the geometry worker writing the file and the SignalR event).
        // Retry up to 4 times on 404 with exponential backoff before surfacing the error to the UI.
        const _retryDelays = CONFIG.GLB_RETRY_DELAYS;
        function _loadAttempt(attempt) {
            // Bail out if a newer initialize() call has superseded this one
            if (loadGenerations[canvasId] !== currentGen) {
                console.warn(`[BabylonViewer] Stale load attempt ${attempt} cancelled (gen mismatch)`);
                return;
            }
            BABYLON.SceneLoader.Append('', _effectiveFileUrl, scene,
                (_scene) => {
                // Check again inside the async success callback — dispose() may have run while loading
                if (loadGenerations[canvasId] !== currentGen) {
                    console.warn('[BabylonViewer] Stale load success ignored (gen mismatch)');
                    return;
                }
                modelLoadState[canvasId] = 'loaded';
                requestAnimationFrame(() => { canvas.style.opacity = '1'; });


                // ── Re-affirm transparent background (append:true keeps existing scene) ──
                _scene.clearColor = new BABYLON.Color4(0, 0, 0, 0);

                // ── Studio lighting + image processing ──
                const shadowGenerator = setupStudioLighting(canvasId, _scene, isDark);
                setupImageProcessing(_scene, isDark);

                // ── Find real model root nodes (TransformNodes or Meshes at scene root) ──
                // Operating on scene.rootNodes guarantees local-space == world-space
                // (no parent transform to account for), making centering exact.
                const _sysNames = new Set(['key', 'fill', 'back', 'hemi', 'cam', '__init_light__']);
                const modelRootNodes = _scene.rootNodes.filter(n =>
                    n.name !== '__grid__' &&
                    !n.name.startsWith('__axis') &&
                    !_sysNames.has(n.name) &&
                    !(n instanceof BABYLON.Camera) &&
                    !(n instanceof BABYLON.Light)
                );

                // rootMeshes still needed for scaling and shadow setup
                const rootMeshes = _scene.meshes.filter(m =>
                    m.name !== '__grid__' && m.name !== '__shadow_catcher__' && !m.name.startsWith('__axis') &&
                    (m.parent == null || !(m.parent instanceof BABYLON.AbstractMesh))
                );

                if (modelRootNodes.length === 0 && rootMeshes.length === 0) {
    console.warn('[BabylonViewer] No model meshes found - GLB may be empty or conversion failed');
    return;
}

                // ── Compute raw bounding box (GLB as-loaded, Y-up, mm) ──
                let rawBb = computeSceneBounds(_scene);
                if (!rawBb) {
    console.warn('[BabylonViewer] Could not compute bounding box - GLB may be corrupt');
    return;
}

                // ── Scale correction (if GLB dimensions deviate >5% from known) ──
                let scaleFactor = 1;
                const rawMaxDim = Math.max(
                    rawBb.max.x - rawBb.min.x,
                    rawBb.max.y - rawBb.min.y,
                    rawBb.max.z - rawBb.min.z
                );
                if (rawMaxDim > 1e-9
                    && knownDimsMm && knownDimsMm.x > 0 && knownDimsMm.y > 0 && knownDimsMm.z > 0) {
                    const knownMax = Math.max(knownDimsMm.x, knownDimsMm.y, knownDimsMm.z);
                    const ratio = rawMaxDim / knownMax;
                    const tol = CONFIG.SCALE_TOLERANCE;
                    if (ratio < (1 - tol) || ratio > (1 + tol)) scaleFactor = knownMax / rawMaxDim;
                }
                if (scaleFactor !== 1) {
                    rootMeshes.forEach(m => m.scaling.setAll(scaleFactor));
                }
                modelScaleFactors[canvasId] = scaleFactor;

                // ── Apply +90°X rotation to model root nodes ──
                // GLBs are Y-up (glTF spec). +90°X converts to Z-up (CAD/print standard).
                // Root nodes have no parent, so local-space == world-space for this rotation.
                const zUpQuat = BABYLON.Quaternion.RotationAxis(BABYLON.Axis.X, Math.PI / 2);
                const targetNodes = modelRootNodes.length > 0 ? modelRootNodes : rootMeshes;
                targetNodes.forEach(n => {
                    if (n.rotationQuaternion == null) {
                        n.rotationQuaternion = (n.rotation && n.rotation.length)
                            ? BABYLON.Quaternion.FromEulerVector(n.rotation)
                            : BABYLON.Quaternion.Identity();
                    }
                    n.rotationQuaternion = zUpQuat.multiply(n.rotationQuaternion);
                });

                // Force world matrix recalculation for all meshes after rotation
                _scene.meshes.forEach(m => m.computeWorldMatrix(true));

                // ── Bounding box (now Z-up, mm) ──
                let bb = computeSceneBounds(_scene);
                if (!bb) return;

                // ── Center on X/Y, lift Z_min → 0 ──
                // Applied to root nodes (local == world), so offset is exact.
                const cx = (bb.min.x + bb.max.x) / 2;
                const cy = (bb.min.y + bb.max.y) / 2;
                const zLift = -bb.min.z;
                modelCenterOffsets[canvasId] = { cx, cy, zLift };
                targetNodes.forEach(n => {
                    n.position.x -= cx;
                    n.position.y -= cy;
                    n.position.z += zLift;
                });

                // ── Final bounding box ──
                _scene.meshes.forEach(m => m.computeWorldMatrix(true));
                const finalBb = computeSceneBounds(_scene);
                if (!finalBb) return;
                sceneBoundingBoxes[canvasId] = finalBb;
                meshCenters[canvasId] = {
                    x: (finalBb.min.x + finalBb.max.x) / 2,
                    y: (finalBb.min.y + finalBb.max.y) / 2,
                    z: (finalBb.min.z + finalBb.max.z) / 2,
                };
                if (turningAxisRequests[canvasId]) {
                    const request = turningAxisRequests[canvasId];
                    buildTurningAxisGeometry(canvasId, request.primaryAxis, request.axisVector, request.axisPoint);
                }

                // ── Permanent shadow-catcher ground plane ──
                // Creates an always-on ground mesh to catch shadows from the model.
                // The grid toggle is independent and creates/disposes its own ground.
                const bbSizeXY = Math.max(finalBb.max.x - finalBb.min.x, finalBb.max.y - finalBb.min.y) * 3;
                const catcher = BABYLON.MeshBuilder.CreateGround('__shadow_catcher__', { width: bbSizeXY, height: bbSizeXY }, _scene);
                catcher.rotation.x = Math.PI / 2;   // world XY plane (Z-up)
                catcher.position.z = finalBb.min.z;  // sit at model base
                catcher.receiveShadows = true;
                catcher.isPickable = false;
                // Prefer ShadowOnlyMaterial (visually invisible but catches shadows)
                if (BABYLON.ShadowOnlyMaterial) {
                    const mat = new BABYLON.ShadowOnlyMaterial('shadowOnly', _scene);
                    mat.shadowColor = new BABYLON.Color3(0, 0, 0);
                    mat.alpha = 0.35;
                    catcher.material = mat;
                } else {
                    // Fallback: transparent StandardMaterial
                    const mat = new BABYLON.StandardMaterial('shadowCatcherFallback', _scene);
                    mat.alpha = 0.0001;
                    mat.diffuseColor = new BABYLON.Color3(1, 1, 1);
                    mat.specularColor = new BABYLON.Color3(0, 0, 0);
                    catcher.material = mat;
                }

                // ── Build body map for multi-body support ──
                // A multi-body GLB has a single glTF __root__ node with N body children.
                // A single-body GLB either IS the root mesh or has one child.
                // We resolve body nodes by descending into children when the root has multiple.
                const bodyMap = new Map();
                let bodyIndex = 0;

                function _collectBodyNodes(root) {
                    // If root is itself a mesh, it IS the body
                    if (root instanceof BABYLON.AbstractMesh && root.getTotalVertices() > 0) {
                        return [root];
                    }
                    // Get non-system child nodes
                    const children = root.getChildren().filter(c =>
                        !(c instanceof BABYLON.Camera) && !(c instanceof BABYLON.Light)
                    );
                    if (children.length === 0) return [];
                    if (children.length === 1) {
                        // One child — could be an extra wrapper level; recurse
                        return _collectBodyNodes(children[0]);
                    }
                    // Multiple children → each is a distinct body
                    return children;
                }

                modelRootNodes.forEach(root => {
                    const bodyNodes = _collectBodyNodes(root);
                    bodyNodes.forEach(bodyNode => {
                        const meshes = bodyNode instanceof BABYLON.AbstractMesh && bodyNode.getTotalVertices() > 0
                            ? [bodyNode, ...bodyNode.getChildMeshes(false).filter(m => m.getTotalVertices() > 0)]
                            : bodyNode.getChildMeshes(false).filter(m => m.getTotalVertices() > 0);
                        if (meshes.length > 0) {
                            bodyMap.set(bodyIndex, {
                                rootNode: bodyNode,
                                meshes,
                                colorMaterial: null,
                                name: bodyNode.name || `Body_${bodyIndex}`
                            });
                            bodyIndex++;
                        }
                    });
                });
                perCanvasBodyMap[canvasId] = bodyMap;
                debugLog(`[BabylonViewer] Detected ${bodyMap.size} bodies in model`);

                // ── Apply multi-body colored materials immediately ──
                // Don't wait for SignalR — color the bodies right away on load
                if (bodyMap.size > 1) {
                    const palette = CONFIG.MULTI_BODY_PALETTE.map(c => toColor3(c));
                    const bodies = Array.from(bodyMap.keys()).map(idx => ({
                        index: idx,
                        name: bodyMap.get(idx)?.name || `Body_${idx}`,
                        volumeCm3: 0,  // Not known yet, but setBodies doesn't use it
                        colorHex: null
                    }));

                    // Apply the colored materials
                    bodies.forEach((body, idx) => {
                        const bodyData = bodyMap.get(body.index);
                        if (!bodyData) return;

                        const color = palette[idx % palette.length];
                        const colorMaterial = new BABYLON.PBRMaterial(`body_${idx}_mat`, scene);
                        colorMaterial.albedoColor = color;
                        colorMaterial.metallic = CONFIG.MATERIAL_MULTI_BODY.metallic;
                        colorMaterial.roughness = CONFIG.MATERIAL_MULTI_BODY.roughness;
                        colorMaterial.alpha = CONFIG.MATERIAL_MULTI_BODY.alpha;
                        colorMaterial.backFaceCulling = false;

                        bodyData.meshes.forEach(mesh => {
                            mesh.material = colorMaterial;
                        });

                        bodyData.colorMaterial = colorMaterial;
                        bodyData.index = idx;
                        bodyData.name = body.name;

                        debugLog(`[BylonViewer] Auto-colored body ${idx} (${body.name}) to RGB(${color.r},${color.g},${color.b})`);
                    });
                }

                // ── Save original materials and setup shadows ──
                const origMats = originalMaterials[canvasId];
                const shadowGen = shadowGenerators[canvasId];
                if (!shadowGen) {
                    console.warn('[BabylonViewer] Shadow generator not found for canvas:', canvasId);
                }
                _scene.meshes.forEach(m => {
                    if (m.name !== '__grid__' && m.name !== '__shadow_catcher__' && !m.name.startsWith('__axis')) {
                        if (m.material) origMats[m.uniqueId] = m.material;
                        if (shadowGen) {
                            shadowGen.addShadowCaster(m);
                        }
                        m.receiveShadows = true;
                    }
                });

                // Capture immutable baseline for "default solid look" — never overwritten.
                // Used by setRenderMode('solid') and flipped-triangles disable to restore a clean state.
                // For single-body models, always use the uniform CAD gray so all files look consistent.
                // For multi-body models, preserve per-body palette colors.
                if (!defaultSolidMaterials[canvasId]) defaultSolidMaterials[canvasId] = new Map();
                const defMap = defaultSolidMaterials[canvasId];
                const existingBodyMap = perCanvasBodyMap[canvasId];
                const isMultiBody = existingBodyMap && existingBodyMap.size > 1;
                const cadGray = getCadMaterial(_scene);
                _scene.meshes.forEach(m => {
                    if (m.material && !defMap.has(m.uniqueId) && !isSystemMesh(m) && m.name !== '__root__' && !m.name.startsWith('__axis')) {
                        defMap.set(m.uniqueId, isMultiBody ? m.material : cadGray);
                        // Apply CAD gray immediately for single-body so the initial view is uniform
                        if (!isMultiBody) m.material = cadGray;
                    }
                });
                tagModelMeshesForAnalysis(canvasId, _scene);

                // Position key light based on bounding box so its shadow frustum covers the model.
                const dist = Math.max(
                    finalBb.max.x - finalBb.min.x,
                    finalBb.max.y - finalBb.min.y,
                    finalBb.max.z - finalBb.min.z
                );
                const keyLight = _scene.getLightByName('key');
                if (keyLight) {
                    keyLight.position = new BABYLON.Vector3(
                        meshCenters[canvasId].x - dist,
                        meshCenters[canvasId].y - dist,
                        finalBb.max.z + dist
                    );
                }

                // ── Configure camera ──
                const cam = mainCameras[canvasId];
                if (cam) {
                    cam.upVector = new BABYLON.Vector3(0, 0, 1);
                    fitCameraToMesh(cam, finalBb, meshCenters[canvasId], canvasId);
                    applyPreset(cam, 'iso');
                    // Apply projection after fit: engines[canvasId] is now set (assigned after
                    // _loadAttempt is started, before the async callback fires), so
                    // setCameraProjection will no longer return early. This also recalculates
                    // ortho bounds using the correct model-scale radius.
                    setCameraProjection(canvasId, viewerSettings.cameraProjection);
                }

                // ── Post Processing ──
                // Engine is already created with hardware MSAA (new BABYLON.Engine(canvas, true)).
                // FXAA is intentionally omitted: it blurs wireframes. SSAO is omitted because it
                // conflicts with the multi-camera setup used for the axis gizmo viewport.

                // ── Auto-rotation: idle spin with hover slow-down and click stop ──
                animStates[canvasId]       = 'idle';
                autoSpeedCurrent[canvasId] = 0;
                autoSpeedTarget[canvasId]  = SPEED_IDLE;

                canvas.addEventListener('mouseenter', () => {
                    if (animStates[canvasId] !== 'interacting') {
                        animStates[canvasId]      = 'hovering';
                        autoSpeedTarget[canvasId] = SPEED_HOVER;
                    }
                });
                canvas.addEventListener('mouseleave', () => {
                    if (animStates[canvasId] !== 'interacting') {
                        animStates[canvasId]      = 'idle';
                        autoSpeedTarget[canvasId] = SPEED_IDLE;
                    }
                });
                canvas.addEventListener('pointerdown', () => {
                    animStates[canvasId]      = 'interacting';
                    autoSpeedTarget[canvasId] = SPEED_STOP;
                });

                // ── Axis gizmo ──
                createAxisGizmo(canvasId, _scene, mainCameras[canvasId], canvas);
                axisGizmoLayer[canvasId]?.onResize(canvas.offsetWidth, canvas.offsetHeight);

                // ── Resize observer ──
                if (resizeObservers[canvasId]) resizeObservers[canvasId].disconnect();
                const ro = new ResizeObserver(() => {
                    requestAnimationFrame(() => {
                        if (engines[canvasId]) {
                            engines[canvasId].resize();
                            axisGizmoLayer[canvasId]?.onResize(canvas.offsetWidth, canvas.offsetHeight);
                        }
                    });
                });
                ro.observe(canvas);
                resizeObservers[canvasId] = ro;

                setRenderMode(canvasId, viewerSettings.renderMode);
                if (viewerSettings.partColor || viewerSettings.processId) {
                    setPartMaterial(canvasId,
                        viewerSettings.processId,
                        viewerSettings.finishCode,
                        viewerSettings.roughnessCode,
                        viewerSettings.partColor);
                }
                toggleEdges(canvasId, !!viewerSettings.edgesEnabled);
                toggleBoundingBox(canvasId, !!viewerSettings.boundingBoxEnabled);
                viewerSettings.gridEnabled ? showGrid(canvasId) : hideGrid(canvasId);
                setSectionPlane(
                    canvasId,
                    !!viewerSettings.sectionEnabled,
                    viewerSettings.sectionAxis,
                    viewerSettings.sectionOffsetMm,
                    !!viewerSettings.sectionInverted
                );
                runLocalAdvisoryGeometry(canvasId, {
                    processCode: viewerSettings.processCode ?? viewerSettings.processId,
                    storagePath: viewerSettings.storagePath,
                    dotNetRef,
                });
            },
            null,
            (_scene, message, exception) => {
                const is404 = message && (message.includes('404') || message.includes('Not Found') || message.includes('status: 404'));
                if (is404 && attempt < _retryDelays.length) {
                    const delay = _retryDelays[attempt];
                    console.warn(`[BabylonViewer] GLB not ready (404), retry ${attempt + 1}/${_retryDelays.length} in ${delay}ms`);
                    setTimeout(() => {
                        if (loadGenerations[canvasId] !== currentGen) return;
                        _loadAttempt(attempt + 1);
                    }, delay);
                    return;
                }
                modelLoadState[canvasId] = 'error';
                const sanitizedUrl = fileUrl ? (fileUrl.includes('?') ? fileUrl.substring(0, fileUrl.indexOf('?')) + '?[SIGNED_URL]' : fileUrl) : '(none)';
                console.warn('[BabylonViewer] Model preview unavailable, showing fallback:', {
                    url: sanitizedUrl,
                    message: message,
                    exception: exception?.message || exception?.toString() || '(no exception)',
                    stack: exception?.stack || '(no stack)',
                    attempt: attempt,
                    totalRetries: _retryDelays.length
                });
                if (dotNetRef) {
                    dotNetRef.invokeMethodAsync('OnLoadError', message || 'Failed to load 3D model');
                }
                requestAnimationFrame(() => { canvas.style.opacity = '1'; });
            },
            forcedExt,
            );
        }
        _loadAttempt(0);

        engine.runRenderLoop(() => {
            if (loadGenerations[canvasId] !== currentGen || engines[canvasId] !== engine || scenes[canvasId] !== scene) {
                return;
            }

            // Smooth speed interpolation (lerp toward target)
            const curr   = autoSpeedCurrent[canvasId] ?? 0;
            const target = autoSpeedTarget[canvasId]  ?? 0;
            autoSpeedCurrent[canvasId] = curr + (target - curr) * CONFIG.AUTO_ROTATION_LERP_FACTOR;

            // Apply auto-rotation
            const cam = mainCameras[canvasId];
            if (cam && Math.abs(autoSpeedCurrent[canvasId]) > CONFIG.AUTO_ROTATION_MIN_THRESHOLD) {
                cam.alpha += autoSpeedCurrent[canvasId];
            }

            scene.render();
        });

        const resizeHandler = () => {
            requestAnimationFrame(() => {
                if (engines[canvasId]) {
                    engines[canvasId].resize();
                    axisGizmoLayer[canvasId]?.onResize(canvas.offsetWidth, canvas.offsetHeight);
                }
            });
        };
        window.addEventListener('resize', resizeHandler);
        engine._resizeHandler = resizeHandler;

        engines[canvasId] = engine;
        scenes[canvasId]  = scene;

    } catch (err) {
        modelLoadState[canvasId] = 'error';
        // Detailed error logging for debugging viewer flash issue
        const sanitizedUrl = fileUrl ? (fileUrl.includes('?') ? fileUrl.substring(0, fileUrl.indexOf('?')) + '?[SIGNED_URL]' : fileUrl) : '(none)';
        console.error('[BabylonViewer] Init failed details:', {
            url: sanitizedUrl,
            error: err?.message || err?.toString() || '(no error)',
            stack: err?.stack || '(no stack)'
        });
        if (dotNetRef) {
            dotNetRef.invokeMethodAsync('OnLoadError', err.message || 'Failed to initialize 3D viewer');
        }
    }
}

// ── Pick-point pan (right-click drag) ─────────────────────────────────────────────

/**
 * Attaches a right-click drag handler that pans the camera so that the
 * 3D world point initially under the cursor stays exactly under the cursor.
 *
 * Algorithm (ray-plane intersection):
 *   1. On right-mousedown: cast a ray and intersect with a plane that is
 *      perpendicular to the view direction and passes through camera.target.
 *      This gives the "anchor" world point A.
 *   2. On mousemove: cast a ray and find where it hits the same plane.
 *      This gives the "current" world point C.
 *   3. Move camera.target by (A − C) so that C maps to the anchor pixel.
 *      A stays fixed relative to that pixel.
 *
 * Works for both perspective and orthographic modes.
 */
const panStates = {}; // canvasId → { active, plane, anchor, planeNormal }
// per-canvas right-drag event listeners so we can remove them on dispose
const panHandlers = {}; // canvasId → { down, move, up }
const middleZoomHandlers = {}; // DISABLED - feature removed

function attachPickPointPan(canvasId, canvas, camera) {
    // Remove any previous handlers for this canvas
    const prev = panHandlers[canvasId];
    if (prev) {
        canvas.removeEventListener('pointerdown',  prev.down);
        canvas.removeEventListener('pointermove',  prev.move);
        canvas.removeEventListener('pointerup',    prev.up);
        canvas.removeEventListener('contextmenu',  prev.ctx);
    }

    panStates[canvasId] = { active: false, plane: null, anchor: null };

    function castRay(clientX, clientY) {
        const engine = engines[canvasId];
        const scene  = scenes[canvasId];
        if (!engine || !scene) return null;
        const rect = canvas.getBoundingClientRect();
        const x = ((clientX - rect.left) / rect.width)  * engine.getRenderWidth();
        const y = ((clientY - rect.top)  / rect.height) * engine.getRenderHeight();
        return scene.createPickingRay(x, y, BABYLON.Matrix.Identity(), camera, false);
    }

    function rayPlaneIntersect(ray, planeNormal, planePoint) {
        const denom = BABYLON.Vector3.Dot(planeNormal, ray.direction);
        if (Math.abs(denom) < 1e-6) return null;
        const t = BABYLON.Vector3.Dot(planeNormal, planePoint.subtract(ray.origin)) / denom;
        if (t < 0) return null;
        return ray.origin.add(ray.direction.scale(t));
    }

    const onPointerDown = (e) => {
        if (e.button !== 2) return;
        e.preventDefault();
        const state = panStates[canvasId];
        const ray = castRay(e.clientX, e.clientY);
        if (!ray) return;
        // Plane: perpendicular to view direction, passing through camera.target
        const planeNormal = camera.position.subtract(camera.target).normalize();
        const anchor = rayPlaneIntersect(ray, planeNormal, camera.target.clone());
        if (!anchor) return;
        state.active  = true;
        state.plane   = { normal: planeNormal, point: camera.target.clone() };
        state.anchor  = anchor;
        canvas.setPointerCapture(e.pointerId);
    };

    const onPointerMove = (e) => {
        const state = panStates[canvasId];
        if (!state || !state.active) return;
        const ray = castRay(e.clientX, e.clientY);
        if (!ray) return;
        const hit = rayPlaneIntersect(ray, state.plane.normal, state.plane.point);
        if (!hit) return;
        // Move camera.target so the anchor stays fixed under the cursor
        const delta = state.anchor.subtract(hit);
        camera.target.addInPlace(delta);
        // Keep the plane co-moving with the camera target for numerical stability
        state.plane.point.addInPlace(delta);
    };

    const onPointerUp = (e) => {
        if (e.button !== 2) return;
        const state = panStates[canvasId];
        if (state) state.active = false;
        try { canvas.releasePointerCapture(e.pointerId); } catch (_) {}
        // Re-apply edges after pan to catch up on skipped observer updates
        if (edgesEnabled[canvasId] && cameraProjection[canvasId] === 'perspective') {
            toggleEdges(canvasId, true);
        }
    };

    // Suppress the browser context-menu on right-click inside the 3D canvas
    const onContextMenu = (e) => e.preventDefault();

    canvas.addEventListener('pointerdown',  onPointerDown);
    canvas.addEventListener('pointermove',  onPointerMove);
    canvas.addEventListener('pointerup',    onPointerUp);
    canvas.addEventListener('contextmenu',  onContextMenu);

    panHandlers[canvasId] = {
        down: onPointerDown,
        move: onPointerMove,
        up:   onPointerUp,
        ctx:  onContextMenu,
    };
}

// ── Middle-mouse drag zoom ───────────────────────────────────────────────────────

/**
 * Attaches middle-mouse button drag-to-zoom functionality.
 * Dragging up zooms in, dragging down zooms out. Zooms toward the cursor position.
 * @param {string} canvasId
 * @param {HTMLElement} canvas
 */
function attachMiddleMouseZoom(canvasId, canvas) { return; // DISABLED - feature removed
    // Remove any previous handlers for this canvas
    const prev = middleZoomHandlers[canvasId];
    if (prev) {
        canvas.removeEventListener('pointerdown', prev.down);
        canvas.removeEventListener('pointermove', prev.move);
        canvas.removeEventListener('pointerup',   prev.up);
        canvas.removeEventListener('pointerleave', prev.leave);
    }

    const state = {
        active: false,
        startY: 0,
        startRadius: 0,
        startZoom: 0,
        targetPoint: null
    };

    function onPointerDown(e) {
        if (e.button !== 1) return; // middle mouse only
        e.preventDefault();
        state.active = true;
        state.startY = e.clientY;
        state.startRadius = mainCameras[canvasId].radius;
        state.startZoom = orthoZoomFactors[canvasId] || 1;

        // Pick point under cursor for zoom-target
        const scene = scenes[canvasId];
        const coords = getPointerRenderCoordinates(canvasId, e);
        const pickResult = coords
            ? scene.pick(coords.x, coords.y, mesh => isModelMeshForAnalysis(mesh, canvasId))
            : { hit: false };
        if (pickResult.hit && !isSystemMesh(pickResult.pickedMesh)) {
            state.targetPoint = pickResult.pickedPoint.clone();
        } else {
            state.targetPoint = null;
        }

        // Stop auto-rotation
        animStates[canvasId] = 'interacting';
        autoSpeedTarget[canvasId] = SPEED_STOP;
    }

    function onPointerMove(e) {
        if (!state.active) return;
        const dy = state.startY - e.clientY; // positive = drag up = zoom in
        const zoomSpeed = 0.005;
        const cam = mainCameras[canvasId];

        if (cameraProjection[canvasId] === 'orthographic') {
            orthoZoomFactors[canvasId] = Math.max(0.05, state.startZoom * Math.exp(-dy * zoomSpeed));
        } else {
            const newRadius = Math.max(cam.lowerRadiusLimit, Math.min(cam.upperRadiusLimit,
                state.startRadius * Math.exp(dy * zoomSpeed)));
            cam.radius = newRadius;
        }

        // Move target toward picked point (CAD-style zoom-to-cursor)
        if (state.targetPoint) {
            const factor = dy * zoomSpeed * 0.3;
            cam.target = BABYLON.Vector3.Lerp(cam.target, state.targetPoint, Math.min(0.15, Math.abs(factor)));
        }
    }

    function onPointerUp(e) {
        if (e.button !== 1 || !state.active) return;
        state.active = false;
        // Re-apply edges if enabled (zoom changed)
        if (edgesEnabled[canvasId]) toggleEdges(canvasId, true);
    }

    function onPointerLeave() {
        if (state.active) {
            state.active = false;
            // Re-apply edges if enabled
            if (edgesEnabled[canvasId]) toggleEdges(canvasId, true);
        }
    }

    canvas.addEventListener('pointerdown',  onPointerDown);
    canvas.addEventListener('pointermove',  onPointerMove);
    canvas.addEventListener('pointerup',    onPointerUp);
    canvas.addEventListener('pointerleave', onPointerLeave);

    // Prevent middle-click auto-scroll behavior in some browsers
    canvas.onauxclick = (e) => e.preventDefault();

    middleZoomHandlers[canvasId] = {
        down:  onPointerDown,
        move: onPointerMove,
        up:    onPointerUp,
        leave: onPointerLeave,
    };
}

// ── Axis gizmo ────────────────────────────────────────────────────────────────

/**
 * Creates a fixed XYZ axis indicator in the top-right corner.
 * After 90° clockwise rotation around Z (Z is up on screen):
 * - X (red) → points up (Y+)
 * - Y (green) → points right (X+)
 * - Z (blue) → points up (Z+, unchanged)
 */
function createAxisGizmo(canvasId, scene, mainCam, canvas) {
    // Dispose previous
    if (axisGizmoLayer[canvasId]) { axisGizmoLayer[canvasId].dispose(); axisGizmoLayer[canvasId] = null; }
    if (axisLabelDivs[canvasId]) {
        axisLabelDivs[canvasId].forEach(({ div }) => div.remove());
        delete axisLabelDivs[canvasId];
    }
    if (axisMouseHandlers[canvasId]) {
        canvas.removeEventListener('mousemove', axisMouseHandlers[canvasId]);
        canvas.removeEventListener('mouseleave', axisMouseHandlers[canvasId + '_leave']);
        delete axisMouseHandlers[canvasId];
    }
    ['__axisX__','__axisY__','__axisZ__','__axisXArr__','__axisYArr__','__axisZArr__']
        .forEach(n => { const m = scene.getMeshByName(n); if (m) m.dispose(); });
    const oldCam = scene.getCameraByName('__axesCam__');
    if (oldCam) oldCam.dispose();

    if (!(mainCam instanceof BABYLON.ArcRotateCamera)) return;

    const LAYER = CONFIG.AXIS_GIZMO.layerMask;
    const LEN   = CONFIG.AXIS_GIZMO.length;

    // Z-up CAD standard: X=red, Y=green, Z=blue
    const COL_X = toColor3(CONFIG.AXIS_GIZMO.colorX); // Red
    const COL_Y = toColor3(CONFIG.AXIS_GIZMO.colorY); // Green
    const COL_Z = toColor3(CONFIG.AXIS_GIZMO.colorZ); // Blue

    function makeAxisLine(name, pts, color) {
        const l = BABYLON.MeshBuilder.CreateLines(name, { points: pts }, scene);
        l.color = color; l.isPickable = false; l.layerMask = LAYER;
        return l;
    }

    makeAxisLine('__axisX__', [BABYLON.Vector3.Zero(), new BABYLON.Vector3(-LEN, 0, 0)], COL_X);  // X+ direction, red
    makeAxisLine('__axisY__', [BABYLON.Vector3.Zero(), new BABYLON.Vector3(0, LEN, 0)], COL_Y);  // Y+ direction, green
    makeAxisLine('__axisZ__', [BABYLON.Vector3.Zero(), new BABYLON.Vector3(0, 0, LEN)], COL_Z);  // Z+ direction, blue

    function makeCone(name, dir, color) {
        const d = dir.normalize();
        const cone = BABYLON.MeshBuilder.CreateCylinder(name,
            { diameterTop: 0, diameterBottom: CONFIG.AXIS_GIZMO.coneDiameter, height: CONFIG.AXIS_GIZMO.coneHeight, tessellation: CONFIG.AXIS_GIZMO.coneTessellation }, scene);
        const mat = new BABYLON.StandardMaterial(name + 'Mat', scene);
        mat.diffuseColor = color; mat.emissiveColor = color.scale(0.4);
        mat.backFaceCulling = false;
        cone.material = mat; cone.isPickable = false; cone.layerMask = LAYER;
        const up = new BABYLON.Vector3(0, 1, 0);
        const cross = BABYLON.Vector3.Cross(up, d);
        if (cross.length() > 0.001) {
            cone.rotationQuaternion = BABYLON.Quaternion.RotationAxis(
                cross.normalize(), Math.acos(Math.max(-1, Math.min(1, BABYLON.Vector3.Dot(up, d)))));
        } else if (BABYLON.Vector3.Dot(up, d) < 0) {
            cone.rotationQuaternion = BABYLON.Quaternion.RotationAxis(new BABYLON.Vector3(1, 0, 0), Math.PI);
        }
        cone.position = d.scale(LEN + 0.09);
        return cone;
    }

    makeCone('__axisXArr__', new BABYLON.Vector3(-1, 0, 0), COL_X);  // X+ direction, red
    makeCone('__axisYArr__', new BABYLON.Vector3(0, 1, 0), COL_Y);  // Y+ direction, green
    makeCone('__axisZArr__', new BABYLON.Vector3(0, 0, 1), COL_Z);  // Z+ direction, blue

    // Gizmo camera — top-right corner, orthographic, renders only LAYER meshes
    const hw = 1.1;
    const axesCam = new BABYLON.ArcRotateCamera('__axesCam__',
        mainCam.alpha, mainCam.beta, 3.5, BABYLON.Vector3.Zero(), scene);
    axesCam.mode        = BABYLON.Camera.ORTHOGRAPHIC_CAMERA;
    axesCam.orthoLeft   = -hw; axesCam.orthoRight = hw;
    axesCam.orthoTop    = hw;  axesCam.orthoBottom = -hw;
    axesCam.viewport    = new BABYLON.Viewport(
        CONFIG.AXIS_GIZMO.viewportPosition.x,
        CONFIG.AXIS_GIZMO.viewportPosition.y,
        CONFIG.AXIS_GIZMO.viewportPosition.width,
        CONFIG.AXIS_GIZMO.viewportPosition.height
    ); // top-right
    axesCam.layerMask   = LAYER;
    axesCam.minZ = 0.01; axesCam.maxZ = 100;
    axesCam.upVector = new BABYLON.Vector3(0, 0, 1);

    const syncObs = scene.onBeforeRenderObservable.add(() => {
        // Sync the gizmo camera to match the main camera's view direction.
        // We derive a position from the normalised direction vector so the
        // gizmo always shows the correct axis orientation regardless of upVector.
        const dir = mainCam.position.subtract(mainCam.target).normalize();
        axesCam.setPosition(dir.scale(3.5)); // orbit at fixed radius
        axesCam.upVector.copyFrom(mainCam.upVector);
        // Update axis hover label positions each frame
        updateAxisLabels(canvasId, scene, axesCam);
    });

    scene.activeCameras = [mainCam, axesCam];

    // ── Hover labels (X, Y, Z text that appear on mouseover) ──
    const labelDefs = [
        { name: 'X', color: '#f04444', pos: new BABYLON.Vector3(-(LEN + 0.28), 0, 0) },  // X+, red
        { name: 'Y', color: '#22c750', pos: new BABYLON.Vector3(0, LEN + 0.28, 0) },  // Y+, green
        { name: 'Z', color: '#3882f5', pos: new BABYLON.Vector3(0, 0, LEN + 0.28) },  // Z+, blue
    ];

    const labelDivs = labelDefs.map(({ name, color, pos }) => {
        const div = document.createElement('div');
        div.className = 'axis-gizmo-label';
        div.textContent = name;
        div.setAttribute('translate', 'no');
        div.setAttribute('aria-label', `${name} axis`);
        div.lang = 'zxx';
        div.style.cssText = `
            position: fixed;
            transform: translate(-50%, -50%);
            color: ${color};
            font-size: ${CONFIG.AXIS_GIZMO.labelFontSize};
            font-weight: 700;
            font-family: 'JetBrains Mono', ui-monospace, SFMono-Regular, Consolas, 'Courier New', monospace !important;
            font-variant-ligatures: none;
            font-feature-settings: "liga" 0, "clig" 0;
            text-transform: none;
            pointer-events: none;
            opacity: 0;
            transition: opacity 0.18s ease;
            z-index: 25;
            text-shadow: 0 0 4px rgba(0,0,0,0.8);
        `;
        document.body.appendChild(div);
        return { div, localPos: pos };
    });
    axisLabelDivs[canvasId] = labelDivs;

    // Mousemove: show labels when cursor is over axes viewport region
    // BabylonJS viewport (0.78, 0.76, 0.22, 0.24):
    //   canvas DOM coords: relX ≥ 0.78, relY ≤ 1 − 0.76 = 0.24  (BabylonJS Y is bottom-up)
    function onMouseMove(e) {
        const rect = canvas.getBoundingClientRect();
        const relX = (e.clientX - rect.left) / rect.width;
        const relY = (e.clientY - rect.top) / rect.height;
        const inGizmo = relX >= CONFIG.GIZMO_HOVER_REGION.xMin && relY <= CONFIG.GIZMO_HOVER_REGION.yMax;
        labelDivs.forEach(({ div }) => {
            div.style.opacity = inGizmo ? '1' : '0';
        });
    }
    function onMouseLeave() {
        labelDivs.forEach(({ div }) => { div.style.opacity = '0'; });
    }
    canvas.addEventListener('mousemove', onMouseMove);
    canvas.addEventListener('mouseleave', onMouseLeave);
    axisMouseHandlers[canvasId]              = onMouseMove;
    axisMouseHandlers[canvasId + '_leave']   = onMouseLeave;

    axisGizmoLayer[canvasId] = {
        dispose() {
            scene.onBeforeRenderObservable.remove(syncObs);
            scene.activeCameras = [mainCam];
            axesCam.dispose();
            ['__axisX__','__axisY__','__axisZ__','__axisXArr__','__axisYArr__','__axisZArr__']
                .forEach(n => { const m = scene.getMeshByName(n); if (m) m.dispose(); });
            labelDivs.forEach(({ div }) => div.remove());
            canvas.removeEventListener('mousemove', onMouseMove);
            canvas.removeEventListener('mouseleave', onMouseLeave);
        },
        onResize(canvasWidth, canvasHeight) {
            // Keep gizmo axes undistorted: scale ortho bounds to match viewport aspect ratio.
            // Match the camera frustum to the configured gizmo viewport's actual pixel aspect.
            const viewport = CONFIG.AXIS_GIZMO.viewportPosition;
            const viewportWidth = Math.max(1, canvasWidth * viewport.width);
            const viewportHeight = Math.max(1, canvasHeight * viewport.height);
            const aspect = viewportWidth / viewportHeight;
            axesCam.orthoLeft   = -hw * aspect;
            axesCam.orthoRight  =  hw * aspect;
            axesCam.orthoTop    =  hw;
            axesCam.orthoBottom = -hw;
        }
    };
}

/**
 * Reprojects axis label positions to screen space each frame.
 */
function updateAxisLabels(canvasId, scene, axesCam) {
    const labelDivs = axisLabelDivs[canvasId];
    if (!labelDivs) return;
    const engine = engines[canvasId];
    if (!engine) return;
    const canvas = engine.getRenderingCanvas();
    if (!canvas) return;
    const rect = canvas.getBoundingClientRect();
    const rw = engine.getRenderWidth(), rh = engine.getRenderHeight();
    // Use axesCam's own view×projection so labels map to the gizmo viewport.
    const viewProj = axesCam.getViewMatrix().multiply(axesCam.getProjectionMatrix());
    labelDivs.forEach(({ div, localPos }) => {
        const p = BABYLON.Vector3.Project(
            localPos, BABYLON.Matrix.Identity(), viewProj,
            axesCam.viewport.toGlobal(rw, rh)
        );
        if (p.z >= 0 && p.z <= 1) {
            div.style.left = (rect.left + (p.x / rw) * rect.width)  + 'px';
            // BabylonJS viewport.y is in bottom-origin (OpenGL) convention.
            // Subtract it so the gizmo's pixel range [vp.y·rh, rh] maps to CSS [0%, vh%] from top.
            div.style.top  = (rect.top  + (p.y / rh - axesCam.viewport.y) * rect.height) + 'px';
        }
    });
}

