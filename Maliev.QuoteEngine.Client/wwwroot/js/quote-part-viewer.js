/**
 * Reads the --mud-palette-text-primary CSS variable and converts it to a BABYLON.Color4.
 * Falls back to mode-aware hardcoded colors if the variable is missing or unparseable.
 */
function getEdgeColorFromCss(isDark) {
    try {
        const raw = getComputedStyle(document.documentElement)
            .getPropertyValue('--mud-palette-text-primary').trim();
        if (raw) {
            // Use a temporary canvas context to normalize any CSS color format → hex
            const ctx = document.createElement('canvas').getContext('2d');
            ctx.fillStyle = raw;
            const hex = ctx.fillStyle; // browser normalizes to #rrggbb
            const m = hex.match(/^#([0-9a-f]{2})([0-9a-f]{2})([0-9a-f]{2})$/i);
            if (m) return new BABYLON.Color4(
                parseInt(m[1], 16) / 255,
                parseInt(m[2], 16) / 255,
                parseInt(m[3], 16) / 255,
                0.9
            );
        }
    } catch (_) {}
    return isDark
        ? toColor4(CONFIG.EDGES.colorDark)
        : toColor4(CONFIG.EDGES.colorLight);
}

/**
 * Returns the edge width appropriate for the current camera projection.
 * In perspective mode, width scales with camera radius relative to the initial
 * fit-radius so that edges remain visually thin regardless of zoom level.
 * Orthographic renders all edges at equal screen thickness so a fixed narrow
 * value is used.
 */
function getEdgesWidth(canvasId) {
    const fitR = fitRadiusMap[canvasId];
    if (!fitR) return CONFIG.EDGES.defaultWidth;

    let width;
    if (cameraProjection[canvasId] === 'orthographic') {
        const zoomFactor = orthoZoomFactors[canvasId] || 1;
        // Orthographic: use much smaller base width (~1/12 of default) for cleaner look
        const orthoBase = CONFIG.EDGES.defaultWidth * 0.08;
        width = Math.max(CONFIG.EDGES.minWidth, Math.min(orthoBase, orthoBase * zoomFactor));
    } else {
        // Perspective mode: use moderate base width for clean lines without being too thick
        const cam = mainCameras[canvasId];
        const perspBase = CONFIG.EDGES.defaultWidth * 0.4;
        if (!cam) width = perspBase;
        else width = Math.max(CONFIG.EDGES.minWidth, Math.min(perspBase, perspBase * (cam.radius / fitR)));
    }
    return width;
}

/**
 * Returns the polygon offset factor for edge rendering.
 * In orthographic mode a minimal value suffices (depth is linear).
 * In perspective mode with logarithmic depth buffer, we need a much larger factor
 * to push edges above the surface.
 */
function getEdgesZOffset(canvasId) {
    const fitR = fitRadiusMap[canvasId];
    if (!fitR) return 1;

    if (cameraProjection[canvasId] === 'orthographic') {
        const zoomFactor = orthoZoomFactors[canvasId] || 1;
        return Math.max(1, Math.round(1 * Math.sqrt(zoomFactor)));
    }
    // Perspective mode with logarithmic depth: use much larger base offset
    const cam = mainCameras[canvasId];
    if (!cam) return 1000;
    return Math.max(1000, Math.round(1000 * Math.sqrt(cam.radius / fitR)));
}

export function toggleEdges(canvasId, enabled) {
    const scene = scenes[canvasId];
    if (!scene) return;
    edgesEnabled[canvasId] = enabled;
    const edgeColor = getEdgeColorFromCss(darkModes[canvasId]);
    const width = getEdgesWidth(canvasId);
    // zOffset (factor) scales with camera distance in perspective to compensate for
    // non-linear depth precision. zOffsetUnits provides a constant depth bias that
    // prevents Z-fighting on flat faces viewed head-on (where the factor contribution is ~0).
    const zOffset      = getEdgesZOffset(canvasId);
    const zOffsetUnits = cameraProjection[canvasId] === 'orthographic' ? CONFIG.EDGES.zOffsetOrthographic : CONFIG.EDGES.zOffsetPerspective;
    scene.meshes.forEach(mesh => {
        // Skip system meshes: ground grid, axis gizmo parts, bounding box lines
        if (isSystemMesh(mesh)) return;
        if (enabled) {
            try {
                mesh.disableEdgesRendering();
                // Tighter epsilon catches chamfers and shallow draft angles on CAD parts.
                mesh.enableEdgesRendering(CONFIG.EDGES.epsilon, false, zOffset);
                mesh.edgesWidth = width;
                mesh.edgesColor = edgeColor;
                if (mesh._edgesRenderer && 'zOffsetUnits' in mesh._edgesRenderer) {
                    mesh._edgesRenderer.zOffsetUnits = zOffsetUnits;
                }
            } catch (_) {}
        } else {
            safeDisableEdges(mesh);
        }
    });

    // Attach view-matrix observer so edge width updates dynamically as you zoom
    // (works for both orthographic and perspective modes)
    if (enabled) {
        _attachEdgeZoomObserver(canvasId);
    } else {
        _detachEdgeZoomObserver(canvasId);
    }
}

/**
 * Attaches a camera view-matrix observer that re-applies edges width
 * and zOffset every time the user zooms in perspective mode.
 */
function _attachEdgeZoomObserver(canvasId) {
    _detachEdgeZoomObserver(canvasId); // remove any previous
    const cam   = mainCameras[canvasId];
    const scene = scenes[canvasId];
    if (!cam || !scene) return;
    edgeZoomObservers[canvasId] = cam.onViewMatrixChangedObservable.add(() => {
        if (!edgesEnabled[canvasId]) return;
        if (panStates[canvasId]?.active) return;  // Skip during pan to prevent stutter
        const w    = getEdgesWidth(canvasId);
        const zOff = getEdgesZOffset(canvasId);
        scene.meshes.forEach(mesh => {
            if (mesh.name === '__grid__' || mesh.name === '__shadow_catcher__' || mesh.name.startsWith('__axis') || mesh.name.startsWith('bbox_')) return;
            if (mesh._edgesRenderer) {
                mesh.edgesWidth = w;
                mesh._edgesRenderer.zOffset = zOff;
                if ('zOffsetUnits' in mesh._edgesRenderer) {
                    mesh._edgesRenderer.zOffsetUnits = CONFIG.EDGES.zOffsetPerspective;
                }
            }
        });
    });
}

function _detachEdgeZoomObserver(canvasId) {
    if (!edgeZoomObservers[canvasId]) return;
    const cam = mainCameras[canvasId];
    if (cam) cam.onViewMatrixChangedObservable.remove(edgeZoomObservers[canvasId]);
    delete edgeZoomObservers[canvasId];
}

// ── toggleBoundingBox ─────────────────────────────────────────────────────────

export function toggleBoundingBox(canvasId, enabled) {
    if (!enabled) { clearBoundingBox(canvasId); return; }

    const scene  = scenes[canvasId];
    const engine = engines[canvasId];
    const canvas = document.getElementById(canvasId);
    if (!scene || !engine || !canvas) return;

    clearBoundingBox(canvasId);

    const bb = sceneBoundingBoxes[canvasId];
    if (!bb) return;

    const v3 = (x, y, z) => new BABYLON.Vector3(x, y, z);

    // 12 edges of the bounding box (Z-up world: X=width, Y=depth, Z=height)
    const edges = [
        // 4 edges along X (width)
        [v3(bb.min.x, bb.min.y, bb.min.z), v3(bb.max.x, bb.min.y, bb.min.z)],
        [v3(bb.min.x, bb.max.y, bb.min.z), v3(bb.max.x, bb.max.y, bb.min.z)],
        [v3(bb.min.x, bb.min.y, bb.max.z), v3(bb.max.x, bb.min.y, bb.max.z)],
        [v3(bb.min.x, bb.max.y, bb.max.z), v3(bb.max.x, bb.max.y, bb.max.z)],
        // 4 edges along Y (depth)
        [v3(bb.min.x, bb.min.y, bb.min.z), v3(bb.min.x, bb.max.y, bb.min.z)],
        [v3(bb.max.x, bb.min.y, bb.min.z), v3(bb.max.x, bb.max.y, bb.min.z)],
        [v3(bb.min.x, bb.min.y, bb.max.z), v3(bb.min.x, bb.max.y, bb.max.z)],
        [v3(bb.max.x, bb.min.y, bb.max.z), v3(bb.max.x, bb.max.y, bb.max.z)],
        // 4 edges along Z (height)
        [v3(bb.min.x, bb.min.y, bb.min.z), v3(bb.min.x, bb.min.y, bb.max.z)],
        [v3(bb.max.x, bb.min.y, bb.min.z), v3(bb.max.x, bb.min.y, bb.max.z)],
        [v3(bb.min.x, bb.max.y, bb.min.z), v3(bb.min.x, bb.max.y, bb.max.z)],
        [v3(bb.max.x, bb.max.y, bb.min.z), v3(bb.max.x, bb.max.y, bb.max.z)],
    ];

    const gold = new BABYLON.Color4(1, 0.85, 0, 1);
    const lineMesh = BABYLON.MeshBuilder.CreateLineSystem('bbox_lines', {
        lines: edges,
        colors: edges.map(() => [gold, gold]),
        updatable: false
    }, scene);
    lineMesh.isPickable = false;
    bboxLines[canvasId] = lineMesh;

    // Dimension labels — midpoint of each dimension, worldPos is a mutable Vector3
    // so the render observable can reposition them to the camera-facing side each frame.
    const midX = (bb.min.x + bb.max.x) / 2;
    const midY = (bb.min.y + bb.max.y) / 2;
    const midZ = (bb.min.z + bb.max.z) / 2;
    const gap  = Math.max((bb.max.x - bb.min.x) * CONFIG.BBOX_LABEL_GAP_RATIO, CONFIG.BBOX_LABEL_GAP_MIN);

    const labelDefs = [
        { text: `X: ${(bb.max.x - bb.min.x).toFixed(1)} mm`, borderColor: '#f04444' },
        { text: `Y: ${(bb.max.y - bb.min.y).toFixed(1)} mm`, borderColor: '#22c750' },
        { text: `Z: ${(bb.max.z - bb.min.z).toFixed(1)} mm`, borderColor: '#3882f5' },
    ];

    const labelHost = canvas.parentElement ?? document.body;
    const labelEntries = labelDefs.map(({ text, borderColor }) => {
        const div = document.createElement('div');
        div.textContent = text;
        div.style.cssText = `
            position: absolute;
            transform: translate(-50%, -50%);
            background: rgba(10, 10, 14, 0.82);
            color: #f0f0f0;
            font-size: ${CONFIG.AXIS_GIZMO.labelFontSize};
            font-weight: 600;
            font-family: monospace;
            padding: 2px 7px;
            border-radius: 4px;
            border-left: 2px solid ${borderColor};
            pointer-events: none;
            white-space: nowrap;
            z-index: 20;
        `;
        labelHost.appendChild(div);
        // Use mutable Vector3 so each frame we can call .set() with the camera-facing anchor
        return { div, worldPos: new BABYLON.Vector3(midX, bb.min.y - gap, bb.min.z - gap) };
    });

    // Store entries + gap for use in the render observable
    bboxLabels[canvasId] = { entries: labelEntries, gap };

    // Update label world-positions and screen positions every frame
    const cam = mainCameras[canvasId];
    if (cam) {
        const obs = scene.onAfterRenderObservable.add(() => {
            const cvs  = engine.getRenderingCanvas();
            const rect = cvs?.getBoundingClientRect();
            if (!rect || rect.width <= 0 || rect.height <= 0) {
                labelEntries.forEach(({ div }) => { div.style.display = 'none'; });
                return;
            }
            const rw = engine.getRenderWidth(), rh = engine.getRenderHeight();
            // Build view×projection from the main camera explicitly — scene.getTransformMatrix()
            // is unreliable when activeCameras has multiple entries (returns last-rendered camera).
            const viewProj = cam.getViewMatrix().multiply(cam.getProjectionMatrix());

            // Reposition anchors to the camera-facing side of the bounding box each frame
            // so labels are never hidden behind the mesh when the camera orbits.
            const camPos = cam.position;
            const bbLive = sceneBoundingBoxes[canvasId];
            const g = bboxLabels[canvasId]?.gap ?? gap;
            if (bbLive) {
                const anchorY = camPos.y < (bbLive.min.y + bbLive.max.y) / 2 ? bbLive.min.y - g : bbLive.max.y + g;
                const anchorZ = camPos.z > (bbLive.min.z + bbLive.max.z) / 2 ? bbLive.max.z + g : bbLive.min.z - g;
                const anchorX = camPos.x > (bbLive.min.x + bbLive.max.x) / 2 ? bbLive.max.x + g : bbLive.min.x - g;
                const mx = (bbLive.min.x + bbLive.max.x) / 2;
                const my = (bbLive.min.y + bbLive.max.y) / 2;
                const mz = (bbLive.min.z + bbLive.max.z) / 2;
                labelEntries[0].worldPos.set(mx,      anchorY, anchorZ); // X dim label
                labelEntries[1].worldPos.set(anchorX, my,      anchorZ); // Y dim label
                labelEntries[2].worldPos.set(anchorX, anchorY, mz);      // Z dim label
            }

            labelEntries.forEach(({ div, worldPos }) => {
                const p = BABYLON.Vector3.Project(
                    worldPos, BABYLON.Matrix.Identity(), viewProj,
                    cam.viewport.toGlobal(rw, rh)
                );
                if (p.z >= 0 && p.z <= 1) {
                    div.style.left    = ((p.x / rw) * rect.width)  + 'px';
                    div.style.top     = ((p.y / rh) * rect.height) + 'px';
                    div.style.display = '';
                } else {
                    div.style.display = 'none';
                }
            });
        });
        bboxObservers[canvasId] = obs;
    }
}

function clearBoundingBox(canvasId) {
    if (bboxLines[canvasId]) { bboxLines[canvasId].dispose(); delete bboxLines[canvasId]; }
    if (bboxLabels[canvasId]) {
        bboxLabels[canvasId].entries.forEach(({ div }) => div.remove());
        delete bboxLabels[canvasId];
    }
    if (bboxObservers[canvasId]) {
        const scene = scenes[canvasId];
        if (scene) scene.onAfterRenderObservable.remove(bboxObservers[canvasId]);
        delete bboxObservers[canvasId];
    }
}

// ── showGrid / hideGrid ───────────────────────────────────────────────────────

/**
 * Shows a grid floor at the model's base (Z=0 after centering) to visualise
 * the print bed / machine table. Uses a 10mm-spaced GridMaterial.
 * The mesh is named '__grid__' so existing exclusion guards skip it in all
 * bounding-box, render-mode, shadow, and edge-rendering operations.
 */
export function showGrid(canvasId) {
    const scene = scenes[canvasId];
    if (!scene) return;

    // Remove any existing grid first
    const existing = scene.getMeshByName('__grid__');
    if (existing) existing.dispose();

    const bb = sceneBoundingBoxes[canvasId];
    if (!bb) return;

    const sizeX = bb.max.x - bb.min.x;
    const sizeY = bb.max.y - bb.min.y;
    const gridSize = Math.max(sizeX, sizeY) * 3;

    // In Z-up space the floor is the XY plane at z=0 (already the model base after centering).
    // BabylonJS ground lies in the XZ plane by default, so we rotate −90° around X to flip it.
    const ground = BABYLON.MeshBuilder.CreateGround('__grid__', {
        width: gridSize, height: gridSize, subdivisions: 1
    }, scene);
    ground.rotation.x = -Math.PI / 2;
    ground.position.z = 0;
    ground.isPickable = false;
    ground.receiveShadows = true;

    if (typeof BABYLON.GridMaterial !== 'undefined') {
        const mat = new BABYLON.GridMaterial('__grid_mat__', scene);
        mat.majorUnitFrequency = CONFIG.GRID.majorUnitFrequency;
        mat.minorUnitVisibility = CONFIG.GRID.minorUnitVisibility;
        mat.gridRatio = CONFIG.GRID.gridRatio;
        mat.backFaceCulling = false;
        mat.mainColor   = toColor3(CONFIG.GRID.mainColor);
        mat.lineColor   = toColor3(CONFIG.GRID.lineColor);
        mat.opacity     = CONFIG.GRID.opacity;
        ground.material = mat;
        disableSectionClippingForMesh(ground);
    } else {
        // GridMaterial CDN not yet loaded — use a plain transparent material as fallback
        const mat = new BABYLON.StandardMaterial('__grid_mat__', scene);
        mat.alpha = 0.15;
        mat.diffuseColor = new BABYLON.Color3(0.6, 0.6, 0.6);
        mat.backFaceCulling = false;
        ground.material = mat;
        disableSectionClippingForMesh(ground);
    }
}

/**
 * Removes the grid floor mesh from the scene.
 */
export function hideGrid(canvasId) {
    const scene = scenes[canvasId];
    if (!scene) return;
    const grid = scene.getMeshByName('__grid__');
    if (grid) grid.dispose();
}

// ── setCameraProjection ───────────────────────────────────────────────────────

/**
 * Toggle between perspective and orthographic projection for the main camera.
 * In ortho mode the ortho bounds are kept in sync with camera radius so
 * scroll-to-zoom continues to work.
 */
export function setCameraProjection(canvasId, mode) {
    const cam    = mainCameras[canvasId];
    const engine = engines[canvasId];
    debugLog('[BabylonViewer] setCameraProjection:', canvasId, mode, 'cam?', !!cam, 'engine?', !!engine);
    if (!cam || !engine) return;

    cameraProjection[canvasId] = mode;

    if (mode === 'orthographic') {
        const meshRadius = fitRadiusMap[canvasId] || cam.radius;
        orthoZoomFactors[canvasId] = cam.radius / meshRadius;
        const aspect = engine.getAspectRatio(cam);
        const half   = cam.radius * ORTHO_RADIUS_FACTOR;
        cam.mode        = BABYLON.Camera.ORTHOGRAPHIC_CAMERA;
        cam.orthoLeft   = -half * aspect;
        cam.orthoRight  =  half * aspect;
        cam.orthoTop    =  half;
        cam.orthoBottom = -half;
        cam.minZ        = Math.max(meshRadius * CONFIG.CAMERA_NEAR_PLANE, 0.01);

        // Keep ortho bounds in sync when the user zooms — but do NOT move camera!
        // Accumulate zoom factor and compute ortho bounds from it, then reset cam.radius.
        if (!orthoZoomObservers[canvasId]) {
            let _orthoGuard = false;  // prevent recursive observer calls when we reset radius
            orthoZoomObservers[canvasId] = cam.onViewMatrixChangedObservable.add(() => {
                if (cameraProjection[canvasId] !== 'orthographic' || _orthoGuard || _arcAnimGuard[canvasId]) return;
                const initialRadius = fitRadiusMap[canvasId] || cam.radius;
                if (!orthoZoomFactors[canvasId]) orthoZoomFactors[canvasId] = 1.0;

                // Compute how much radius changed (ratio to initial) and accumulate
                const ratio = cam.radius / initialRadius;
                orthoZoomFactors[canvasId] *= ratio;

                // Update ortho bounds from zoom factor, not from moving camera
                const asp = engine.getAspectRatio(cam);
                const h   = initialRadius * orthoZoomFactors[canvasId] * ORTHO_RADIUS_FACTOR;
                cam.orthoLeft   = -h * asp;
                cam.orthoRight  =  h * asp;
                cam.orthoTop    =  h;
                cam.orthoBottom = -h;

                // Reset camera to initial distance — prevents camera from moving into model
                _orthoGuard = true;
                cam.radius = initialRadius;
                cam.minZ    = Math.max(meshRadius * CONFIG.CAMERA_NEAR_PLANE, 0.01);
                _orthoGuard = false;
            });
        }

        // Update near plane dynamically for perspective camera too
        if (!perspZoomObservers[canvasId]) {
            perspZoomObservers[canvasId] = cam.onViewMatrixChangedObservable.add(() => {
                if (cameraProjection[canvasId] === 'orthographic') return;
                if (panStates[canvasId]?.active) return;  // Skip during pan to prevent stutter
                cam.minZ = 0.1;
            });
        }
    } else {
        // Switching to perspective: set radius from ortho zoom level to preserve zoom
        const initialRadius = fitRadiusMap[canvasId];
        if (initialRadius && orthoZoomFactors[canvasId]) {
            cam.radius = initialRadius * orthoZoomFactors[canvasId];
        }
        cam.mode = BABYLON.Camera.PERSPECTIVE_CAMERA;
        cam.minZ  = 0.01;
    }

    // Re-apply edges at the width suitable for the new projection mode.
    if (edgesEnabled[canvasId]) toggleEdges(canvasId, true);
}

// ── DFM Overlays ──────────────────────────────────────────────────────────────
// overlayMeshes[canvasId] → Map<overlayKey, BABYLON.AbstractMesh[]>
// overlayLoading[canvasId] → Set<overlayKey> (prevents concurrent loads)
// overlayIntendedVisible[canvasId] → Map<overlayKey, boolean> (handles race: hide before lazy load)
const overlayMeshes          = {};
const overlayLoading         = {};
const overlayIntendedVisible = {};

// Per-category PBR material overrides for DFM overlays.
// Keys are the category suffix (everything after the last "__" in the overlay key).
// If a key is absent the default red style is used.
const OVERLAY_STYLES = {
    overhang_support: {
        albedo:   () => new BABYLON.Color3(0.12, 0.55, 0.95), // support blue
        alpha:    0.34,
        emissive: () => new BABYLON.Color3(0.02, 0.08, 0.16),
        zOffset:  -6,
    },
    support_required: {
        albedo:   () => new BABYLON.Color3(0.12, 0.55, 0.95), // support blue
        alpha:    0.34,
        emissive: () => new BABYLON.Color3(0.02, 0.08, 0.16),
        zOffset:  -6,
    },
};

/**
 * Toggles a DFM overlay GLB on the scene. Lazy-loads on first show.
 * @param {string} canvasId
 * @param {string} overlayKey  e.g. "FDM__thin_wall"
 * @param {string} glbUrl      Signed URL to the overlay GLB
 * @param {boolean} visible    true = show, false = hide
 */
export async function toggleDfmOverlay(canvasId, partKey, overlayKey, glbUrl, visible) {
    const scene = scenes[canvasId];
    if (!scene) return;

    // Use a composite slot so each part's overlays never collide with another part's.
    const slot = `${canvasId}::${partKey}`;
    overlayMeshes[slot]          ??= new Map();
    overlayLoading[slot]         ??= new Set();
    overlayIntendedVisible[slot] ??= new Map();

    // Always record the intended visibility so the post-load callback can apply it.
    overlayIntendedVisible[slot].set(overlayKey, visible);

    const existing = overlayMeshes[slot].get(overlayKey);
    if (existing) {
        existing.forEach(m => { m.isVisible = visible; });
        return;
    }

    if (!visible) return; // nothing to load for a hide-before-load request

    if (overlayLoading[slot].has(overlayKey)) return; // already loading
    overlayLoading[slot].add(overlayKey);

    try {
        const result = await BABYLON.SceneLoader.ImportMeshAsync('', '', glbUrl, scene, null, '.glb');
        const meshes = result.meshes.filter(m => m.getTotalVertices() > 0);

        // Apply the same three transforms that initialize applies to the main model
        // so overlays align perfectly in world space.
        const scaleFactor = modelScaleFactors[canvasId] ?? 1;
        const offset = modelCenterOffsets[canvasId] ?? { cx: 0, cy: 0, zLift: 0 };
        const zUpQuat = BABYLON.Quaternion.RotationAxis(BABYLON.Axis.X, Math.PI / 2);

        const overlayRoots = result.meshes.filter(m => !m.parent);
        overlayRoots.forEach(n => {
            if (scaleFactor !== 1) n.scaling.setAll(scaleFactor);
            if (n.rotationQuaternion == null) {
                n.rotationQuaternion = (n.rotation && n.rotation.length)
                    ? BABYLON.Quaternion.FromEulerVector(n.rotation)
                    : BABYLON.Quaternion.Identity();
            }
            n.rotationQuaternion = zUpQuat.multiply(n.rotationQuaternion);
            n.position.x -= offset.cx;
            n.position.y -= offset.cy;
            n.position.z += offset.zLift;
        });
        result.meshes.forEach(m => m.computeWorldMatrix(true));

        const isMultiBody = overlayKey === 'GENERAL__multi_body';
        meshes.forEach(mesh => {
            const mat = new BABYLON.PBRMaterial(`dfm_${overlayKey}_mat`, scene);
            mat.metallic        = 0;
            mat.roughness       = 0.8;
            mat.backFaceCulling = false;
            if (isMultiBody) {
                // Multi-body overlay: honour per-body vertex colours baked into the GLB.
                mat.useVertexColors = true;
                mat.albedoColor     = new BABYLON.Color3(1, 1, 1); // multiply with vertex colour
                mat.alpha           = 0.85;
                mat.emissiveColor   = new BABYLON.Color3(0, 0, 0);
                mat.zOffset         = 0; // bodies sit on the model surface — no depth bias needed
            } else {
                // Process-specific DFM issue: look up per-category style, fall back to red.
                mat.useVertexColors = false;
                const categorySuffix = overlayKey.includes('__')
                    ? overlayKey.split('__').slice(1).join('__')
                    : overlayKey;
                const style = OVERLAY_STYLES[categorySuffix];
                if (style) {
                    mat.albedoColor  = style.albedo();
                    mat.alpha        = style.alpha;
                    mat.emissiveColor = style.emissive();
                    mat.zOffset      = style.zOffset;
                    if (categorySuffix === 'overhang_support' || categorySuffix === 'support_required') {
                        mat.transparencyMode = BABYLON.Material.MATERIAL_ALPHABLEND;
                        mat.needDepthPrePass = false;
                    }
                } else {
                    mat.albedoColor  = new BABYLON.Color3(0.95, 0.10, 0.05); // red
                    mat.alpha        = 0.55;
                    mat.emissiveColor = new BABYLON.Color3(0.25, 0.00, 0.00); // faint red glow
                    mat.zOffset      = -2; // depth bias: overlay wins depth test against coplanar main mesh
                }
            }
            mesh.material = mat;
            mesh.isPickable = false;
        });

        overlayMeshes[slot].set(overlayKey, meshes);
        // Apply the most-recent intended visibility (may have been toggled off while loading).
        const shouldShow = overlayIntendedVisible[slot]?.get(overlayKey) ?? true;
        if (!shouldShow) meshes.forEach(m => { m.isVisible = false; });
    } catch (err) {
        console.error(`[BabylonViewer] Failed to load overlay ${overlayKey}:`, err);
    } finally {
        overlayLoading[slot].delete(overlayKey);
    }
}

/**
 * Removes all DFM overlay meshes for the given canvas.
 * @param {string} canvasId
 */
export function clearDfmOverlays(canvasId, partKey) {
    const slot = partKey ? `${canvasId}::${partKey}` : canvasId;
    const map = overlayMeshes[slot];
    if (map) {
        map.forEach(meshes => meshes.forEach(m => {
            if (!m || (typeof m.isDisposed === 'function' && m.isDisposed())) return;
            try {
                m.dispose();
            } catch (error) {
                debugLog('clearDfmOverlays dispose skipped', error);
            }
        }));
        map.clear();
        delete overlayMeshes[slot];
    }
    if (overlayLoading[slot]) { overlayLoading[slot].clear(); delete overlayLoading[slot]; }
    if (overlayIntendedVisible[slot]) { overlayIntendedVisible[slot].clear(); delete overlayIntendedVisible[slot]; }
}

