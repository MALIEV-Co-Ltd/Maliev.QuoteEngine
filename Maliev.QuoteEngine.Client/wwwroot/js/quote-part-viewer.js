function projectWorldPointToScreen(worldPos, canvasId) {
    const cam = mainCameras[canvasId];
    const engine = engines[canvasId];
    if (!cam || !engine) return null;

    const canvas = engine.getRenderingCanvas();
    if (!canvas) return null;

    const rect = canvas.getBoundingClientRect();
    const rw = engine.getRenderWidth();
    const rh = engine.getRenderHeight();
    const viewProj = cam.getViewMatrix().multiply(cam.getProjectionMatrix());
    const projected = BABYLON.Vector3.Project(
        worldPos,
        BABYLON.Matrix.Identity(),
        viewProj,
        cam.viewport.toGlobal(rw, rh)
    );

    if (projected.z < 0 || projected.z > 1) return null;
    return {
        x: rect.left + (projected.x / rw) * rect.width,
        y: rect.top + (projected.y / rh) * rect.height,
    };
}

function projectTurningAxisLabel(div, worldPos, canvasId, visible) {
    if (!visible) {
        div.style.display = 'none';
        return;
    }

    const projected = projectWorldPointToScreen(worldPos, canvasId);
    if (!projected) {
        div.style.display = 'none';
        return;
    }

    div.style.left = `${projected.x}px`;
    div.style.top = `${projected.y}px`;
    div.style.display = '';
}

function distancePointToSegmentPx(px, py, a, b) {
    const dx = b.x - a.x;
    const dy = b.y - a.y;
    const len2 = dx * dx + dy * dy;
    if (len2 <= 1e-6) return Math.hypot(px - a.x, py - a.y);

    const t = Math.max(0, Math.min(1, ((px - a.x) * dx + (py - a.y) * dy) / len2));
    const x = a.x + t * dx;
    const y = a.y + t * dy;
    return Math.hypot(px - x, py - y);
}

function isPointerNearTurningAxis(canvasId, state, pointerEvent) {
    const start = projectWorldPointToScreen(state.start, canvasId);
    const end = projectWorldPointToScreen(state.end, canvasId);
    if (!start || !end) return false;

    return distancePointToSegmentPx(
        pointerEvent.clientX,
        pointerEvent.clientY,
        start,
        end
    ) <= TURNING_AXIS_HOVER_DISTANCE_PX;
}

function updateTurningAxisSvg(canvasId, state) {
    const start = projectWorldPointToScreen(state.start, canvasId);
    const end = projectWorldPointToScreen(state.end, canvasId);

    if (!start || !end) {
        state.svg.style.display = 'none';
        state.labels.forEach(label => projectTurningAxisLabel(label.div, label.worldPos, canvasId, false));
        return;
    }

    state.svg.style.display = '';
    state.line.setAttribute('x1', start.x.toString());
    state.line.setAttribute('y1', start.y.toString());
    state.line.setAttribute('x2', end.x.toString());
    state.line.setAttribute('y2', end.y.toString());
    state.labels.forEach(label => projectTurningAxisLabel(label.div, label.worldPos, canvasId, state.hovered));
}

function buildTurningAxisGeometry(canvasId, primaryAxis, axisVector, axisPoint) {
    const scene = scenes[canvasId];
    const bb = sceneBoundingBoxes[canvasId];
    const centerData = meshCenters[canvasId];
    if (!scene || !bb || !centerData) return false;

    const fallbackCenter = toWorldPoint(centerData);
    const resolvedAxis = resolveTurningAxis(scene, canvasId, primaryAxis, axisVector, axisPoint, bb, fallbackCenter);
    const direction = resolvedAxis?.direction;
    if (!direction) {
        clearTurningAxis(canvasId, false);
        return false;
    }

    clearTurningAxis(canvasId, false);

    const center = resolvedAxis.center ?? fallbackCenter;
    const min = toWorldPoint(bb.min);
    const max = toWorldPoint(bb.max);
    const corners = getBoundingBoxCorners(bb);

    let minDot = Infinity;
    let maxDot = -Infinity;
    corners.forEach(corner => {
        const dot = BABYLON.Vector3.Dot(corner.subtract(center), direction);
        minDot = Math.min(minDot, dot);
        maxDot = Math.max(maxDot, dot);
    });

    const diagonal = max.subtract(min).length();
    const padding = Math.max(diagonal * 0.08, 8);
    const start = center.add(direction.scale(minDot - padding));
    const end = center.add(direction.scale(maxDot + padding));
    const length = BABYLON.Vector3.Distance(start, end);

    const overlay = createTurningAxisSvg();
    const axisLabel = createTurningAxisLabel('Axis of Turning');
    const labelPositions = [
        { div: axisLabel, worldPos: center.add(direction.scale(length * 0.10)) },
    ];

    const state = {
        svg: overlay.svg,
        line: overlay.line,
        labels: labelPositions,
        pointerObserver: null,
        renderObserver: null,
        canvasLeaveHandler: null,
        hovered: false,
        start,
        end,
    };

    state.pointerObserver = scene.onPointerObservable.add(pointerInfo => {
        if (pointerInfo.type !== BABYLON.PointerEventTypes.POINTERMOVE) return;
        state.hovered = pointerInfo.event
            ? isPointerNearTurningAxis(canvasId, state, pointerInfo.event)
            : false;
    });
    const canvas = engines[canvasId]?.getRenderingCanvas();
    if (canvas) {
        state.canvasLeaveHandler = () => { state.hovered = false; };
        canvas.addEventListener('pointerleave', state.canvasLeaveHandler);
    }
    state.renderObserver = scene.onBeforeRenderObservable.add(() => {
        updateTurningAxisSvg(canvasId, state);
    });
    updateTurningAxisSvg(canvasId, state);

    turningAxisLayers[canvasId] = state;
    return true;
}

export function setTurningAxis(canvasId, primaryAxis, axisVector, axisPoint) {
    turningAxisRequests[canvasId] = { primaryAxis, axisVector, axisPoint };
    buildTurningAxisGeometry(canvasId, primaryAxis, axisVector, axisPoint);
}

export function clearTurningAxis(canvasId, clearRequest = true) {
    const state = turningAxisLayers[canvasId];
    if (state) {
        const scene = scenes[canvasId];
        const canvas = engines[canvasId]?.getRenderingCanvas();
        if (state.pointerObserver && scene) scene.onPointerObservable.remove(state.pointerObserver);
        if (state.renderObserver && scene) scene.onBeforeRenderObservable.remove(state.renderObserver);
        if (state.canvasLeaveHandler && canvas) canvas.removeEventListener('pointerleave', state.canvasLeaveHandler);
        if (state.svg) { try { state.svg.remove(); } catch (_) {} }
        state.labels.forEach(({ div }) => { try { div.remove(); } catch (_) {} });
        delete turningAxisLayers[canvasId];
    }

    if (clearRequest) delete turningAxisRequests[canvasId];
}

/**
 * Resolves the BabylonJS loader extension from the caller-supplied hint or the URL path.
 * Falls back to extracting the extension from the URL before any query string.
 */
function resolveExtension(fileUrl, fileExt) {
    const known = ['.glb', '.gltf', '.stl', '.obj', '.3mf'];
    const lower = (fileExt || '').toLowerCase();
    if (known.includes(lower)) return lower;
    const path = (fileUrl || '').split('?')[0].toLowerCase();
    return known.find(e => path.endsWith(e)) ?? '';
}

/**
 * Camera fitting: set radius so the mesh is comfortably framed by the FOV.
 * @param {string|null} canvasId  When provided, stores the fit radius for dynamic edge scaling.
 */
function fitCameraToMesh(cam, bb, meshCenter, canvasId) {
    const w = bb.max.x - bb.min.x;
    const d = bb.max.y - bb.min.y;
    const h = bb.max.z - bb.min.z;
    const halfDiag = Math.sqrt(w * w + d * d + h * h) / 2;
    const fov = cam.fov || CONFIG.CAMERA_FOV;
    const meshRadius = Math.max(halfDiag / Math.tan(fov / 2) * 1.2, 1);

    // Z-up target: center horizontally, vertically at half-height
    cam.target = new BABYLON.Vector3(
        (bb.min.x + bb.max.x) / 2,
        (bb.min.y + bb.max.y) / 2,
        (bb.min.z + bb.max.z) / 2
    );
    cam.radius = meshRadius;
    cam.lowerRadiusLimit = meshRadius * CONFIG.CAMERA_LOWER_RADIUS_LIMIT;
    cam.upperRadiusLimit = meshRadius * CONFIG.CAMERA_UPPER_RADIUS_LIMIT;
    // Use wheelDeltaPercentage for consistent zoom speed across all model sizes
    cam.wheelDeltaPercentage = CONFIG.ZOOM_STEP_PERCENTAGE;
    cam.pinchPrecision = CONFIG.CAMERA_PINCH_PRECISION;
    cam.minZ = 0.1;
    cam.maxZ = meshRadius * CONFIG.CAMERA_FAR_PLANE;
    // Store initial radius for dynamic perspective edge width scaling
    if (canvasId != null) fitRadiusMap[canvasId] = meshRadius;
}

/**
 * Z-up preset definitions — position-based to avoid BabylonJS Y-up spherical coord confusion.
 * `dir` is the unit direction vector FROM target TO camera in world space (Z-up, mm).
 * Z-up world: X=right, Y=depth (−Y=front, +Y=back), Z=up.
 *
 *   front : camera at −Y (in front of model, looking back)
 *   back  : camera at +Y (behind model)
 *   right : camera at +X
 *   left  : camera at −X
 *   top   : camera at +Z (directly above, looking down)
 *   bottom: camera at −Z (directly below, looking up)
 *   iso   : camera at (+1,−1,+1)/√3 — front-right-above, standard 35.26° isometric
 *
 * `up` is the desired screen "up" direction for each view.
 */
// Iso elevation ≈ 25° from horizontal — lower than the 35.26° true isometric for a
// more natural "eye level" viewpoint while still showing the part's top surface.
const _ISO_ELEV = 25 * Math.PI / 180;
const _ISO_Z = Math.sin(_ISO_ELEV);                 // ≈ 0.4226
const _ISO_XY = Math.cos(_ISO_ELEV) / Math.SQRT2;   // ≈ 0.6408
const PRESETS = {
    front:  { dir: [  0,      -1,       0      ], up: [0, 0, 1], zoom: 1.0 },
    back:   { dir: [  0,      +1,       0      ], up: [0, 0, 1], zoom: 1.0 },
    right:  { dir: [ -1,       0,       0      ], up: [0, 0, 1], zoom: 1.0 },
    left:   { dir: [ +1,       0,       0      ], up: [0, 0, 1], zoom: 1.0 },
    top:    { dir: [  0,       0,      +1      ], up: [0, 1, 0], zoom: 1.0 },
    bottom: { dir: [  0,       0,      -1      ], up: [0, 1, 0], zoom: 1.0 },
    iso:    { dir: [ -_ISO_XY, -_ISO_XY, _ISO_Z], up: [0, 0, 1], zoom: 1.0 },
};

// ── Smooth Transition Helpers ─────────────────────────────────────────────────────

/**
 * Creates a smooth easing function for camera transitions (ease-in-out cubic).
 */
function easeInOutCubic(t) {
    return t < 0.5 ? 4 * t * t * t : 1 - Math.pow(-2 * t + 2, 3) / 2;
}

/**
 * Animates camera position to a target position over the configured duration.
 * Returns a Promise that resolves when animation completes.
 */
function animateCameraToPosition(cam, targetPos, scene) {
    return new Promise((resolve) => {
        const duration = CONFIG.CAMERA_TRANSITION_DURATION * 1000;
        const startPos = cam.position.clone();
        const startTime = performance.now();

        const anim = () => {
            if (cam._presetAnimationCancelled) {
                resolve();
                return;
            }
            const elapsed = performance.now() - startTime;
            const progress = Math.min(elapsed / duration, 1);
            const eased = easeInOutCubic(progress);

            cam.position = BABYLON.Vector3.Lerp(startPos, targetPos, eased);

            if (progress < 1) {
                requestAnimationFrame(anim);
            } else {
                resolve();
            }
        };
        anim();
    });
}

/**
 * Animates the camera along a great-circle arc to a target direction, using
 * quaternion SLERP for numerically stable rotation at any angle (including 180°).
 * Also interpolates zoom (radius for perspective, ortho bounds for orthographic).
 * Returns a Promise that resolves when animation completes.
 *
 * @param {BABYLON.ArcRotateCamera} cam
 * @param {number[]} targetDir  - [x,y,z] unit direction from target to camera
 * @param {number}   startRadius - current camera radius
 * @param {number}   endRadius   - target camera radius (fitRadius × preset zoom)
 * @param {string}   canvasId    - viewer canvas ID (for ortho/perspective handling)
 */
function animateCameraArc(cam, targetDir, startRadius, endRadius, canvasId) {
    return new Promise((resolve) => {
        const duration = CONFIG.CAMERA_TRANSITION_DURATION * 1000;
        const tgt = cam.target;

        const startDirVec = cam.position.subtract(tgt).normalize();
        const endDirVec = new BABYLON.Vector3(targetDir[0], targetDir[1], targetDir[2]);

        // Build the quaternion that rotates startDir → endDir
        let dot = BABYLON.Vector3.Dot(startDirVec, endDirVec);
        dot = Math.max(-1, Math.min(1, dot));

        let rotQuat;
        if (dot > 0.999999) {
            // Nearly identical — no rotation
            rotQuat = BABYLON.Quaternion.Identity();
        } else if (dot < -0.999999) {
            // Antipodal (180°): pick a perpendicular axis to define the great circle.
            // Prefer the Z-up axis for horizontal 180° turns (front↔back, left↔right).
            let axis = BABYLON.Vector3.Cross(new BABYLON.Vector3(0, 0, 1), startDirVec);
            if (axis.length() < 0.001) {
                axis = BABYLON.Vector3.Cross(new BABYLON.Vector3(0, 1, 0), startDirVec);
            }
            axis.normalize();
            rotQuat = BABYLON.Quaternion.RotationAxis(axis, Math.PI);
        } else {
            const axis = BABYLON.Vector3.Cross(startDirVec, endDirVec).normalize();
            const angle = Math.acos(dot);
            rotQuat = BABYLON.Quaternion.RotationAxis(axis, angle);
        }

        const identity = BABYLON.Quaternion.Identity();

        // Ortho-mode zoom handling: animate orthoZoomFactors and bounds directly
        const isOrtho = canvasId && cameraProjection[canvasId] === 'orthographic';
        const initialRadius = canvasId ? (fitRadiusMap[canvasId] || cam.radius) : cam.radius;
        const startOrthoZoom = isOrtho ? (orthoZoomFactors[canvasId] || 1.0) : 0;
        const endOrthoZoom = isOrtho ? (endRadius / initialRadius) : 0;
        const engine = isOrtho ? engines[canvasId] : null;

        // Guard the ortho observer so it doesn't fight our bounds updates
        if (isOrtho) _arcAnimGuard[canvasId] = true;

        const startTime = performance.now();

        const anim = () => {
            if (cam._presetAnimationCancelled) {
                if (isOrtho) _arcAnimGuard[canvasId] = false;
                resolve();
                return;
            }

            const elapsed = performance.now() - startTime;
            const progress = Math.min(elapsed / duration, 1);
            const eased = easeInOutCubic(progress);

            // Quaternion SLERP gives a stable arc for any angle, including 180°
            const quat = BABYLON.Quaternion.Slerp(identity, rotQuat, eased);
            const dir = BABYLON.Vector3.Zero();
            startDirVec.rotateByQuaternionToRef(quat, dir);

            // Interpolate radius (perspective zoom) or use constant initial (ortho)
            const currentRadius = isOrtho
                ? initialRadius
                : startRadius + (endRadius - startRadius) * eased;

            cam.setPosition(new BABYLON.Vector3(
                tgt.x + dir.x * currentRadius,
                tgt.y + dir.y * currentRadius,
                tgt.z + dir.z * currentRadius
            ));

            if (isOrtho && engine) {
                // Smoothly animate ortho bounds instead of letting the observer handle it
                const currentZoom = startOrthoZoom + (endOrthoZoom - startOrthoZoom) * eased;
                orthoZoomFactors[canvasId] = currentZoom;
                const h = initialRadius * currentZoom * ORTHO_RADIUS_FACTOR;
                const asp = engine.getAspectRatio(cam);
                cam.orthoLeft   = -h * asp;
                cam.orthoRight  =  h * asp;
                cam.orthoTop    =  h;
                cam.orthoBottom = -h;
                cam.radius = initialRadius;
            } else {
                cam.radius = currentRadius;
            }

            if (progress < 1) {
                requestAnimationFrame(anim);
            } else {
                if (isOrtho) _arcAnimGuard[canvasId] = false;
                resolve();
            }
        };
        anim();
    });
}

