/**
 * Projects a 3D world position to 2D screen coordinates and positions an HTML element there.
 * Used for floating labels that follow 3D points (measure tool, thickness analysis).
 * @param {HTMLElement} div - The HTML element to position
 * @param {BABYLON.Vector3} worldPos - The 3D world position to track
 * @param {string} canvasId - Canvas identifier
 */
function updateLabelPosition(div, worldPos, canvasId) {
    const cam = mainCameras[canvasId];
    const engine = engines[canvasId];
    if (!cam || !engine) return;
    const canvas = engine.getRenderingCanvas();
    if (!canvas) return;
    const rect = canvas.getBoundingClientRect();
    const rw = engine.getRenderWidth(), rh = engine.getRenderHeight();
    const viewProj = cam.getViewMatrix().multiply(cam.getProjectionMatrix());
    const p = BABYLON.Vector3.Project(
        worldPos, BABYLON.Matrix.Identity(), viewProj,
        cam.viewport.toGlobal(rw, rh)
    );
    if (p.z >= 0 && p.z <= 1) {
        div.style.left = (rect.left + (p.x / rw) * rect.width) + 'px';
        div.style.top  = (rect.top  + (p.y / rh) * rect.height) + 'px';
        div.style.display = '';
    } else {
        div.style.display = 'none';
    }
}

