function terminateLocalAdvisoryWorker(canvasId) {
    try { localAdvisoryWorkers[canvasId]?.terminate?.(); } catch (_) {}
    delete localAdvisoryWorkers[canvasId];
}

function analyzeWithLocalAdvisoryWorker(canvasId, workerUrl, wasmUrl, input, processCode, timeoutMs) {
    terminateLocalAdvisoryWorker(canvasId);

    return new Promise((resolve, reject) => {
        const worker = new Worker(workerUrl, { name: 'maliev-geometry-advisory' });
        localAdvisoryWorkers[canvasId] = worker;
        const messageId = `${canvasId}:${Date.now()}:${Math.random().toString(36).slice(2)}`;
        const timeout = setTimeout(() => {
            terminateLocalAdvisoryWorker(canvasId);
            reject(new Error('Local advisory geometry runtime timed out.'));
        }, timeoutMs);

        worker.onmessage = event => {
            const message = event.data ?? {};
            if (message.id !== messageId) return;
            clearTimeout(timeout);
            terminateLocalAdvisoryWorker(canvasId);
            message.ok ? resolve(message.result) : reject(new Error(message.error || 'Local advisory geometry runtime failed.'));
        };
        worker.onerror = event => {
            clearTimeout(timeout);
            terminateLocalAdvisoryWorker(canvasId);
            reject(new Error(event?.message || 'Local advisory geometry worker failed.'));
        };
        worker.postMessage({ id: messageId, input, processCode, wasmUrl });
    });
}

function isBrowserFirstRuntimeContract(value) {
    return value?.isAuthoritative === false &&
        value?.authority === 'local_primary' &&
        value?.executionMode === 'primary_interactive';
}

function normalizeAdvisoryFileBytes(fileBytes) {
    if (!fileBytes) return null;
    if (typeof Uint8Array !== 'undefined' && fileBytes instanceof Uint8Array) return fileBytes;
    if (typeof ArrayBuffer !== 'undefined') {
        if (fileBytes instanceof ArrayBuffer) return new Uint8Array(fileBytes);
        if (typeof ArrayBuffer.isView === 'function' && ArrayBuffer.isView(fileBytes)) {
            return new Uint8Array(fileBytes.buffer, fileBytes.byteOffset ?? 0, fileBytes.byteLength ?? fileBytes.length);
        }
    }
    if (Array.isArray(fileBytes) && typeof Uint8Array !== 'undefined') return Uint8Array.from(fileBytes);
    return fileBytes;
}

function hasAdvisoryFileBytes(fileBytes) {
    return Number(fileBytes?.byteLength ?? fileBytes?.length ?? 0) > 0;
}

function resolveLocalAdvisoryDeviceProfileName() {
    const viewport = typeof window !== 'undefined' ? window : null;
    const root = typeof document !== 'undefined' ? document.documentElement : null;
    const width = Number(viewport?.innerWidth ?? root?.clientWidth ?? 0);
    const height = Number(viewport?.innerHeight ?? root?.clientHeight ?? 0);
    const minSide = width > 0 && height > 0 ? Math.min(width, height) : 0;
    const coarsePointer = typeof matchMedia === 'function' && matchMedia('(pointer: coarse)').matches;

    if (coarsePointer && minSide > 0 && minSide < 768) return 'mobile';
    if (coarsePointer || (width > 0 && width < 1180)) return 'tablet';
    return 'desktop';
}

function resolveLocalAdvisoryDeviceProfile(manifest) {
    return manifest?.deviceProfiles?.[resolveLocalAdvisoryDeviceProfileName()] ?? null;
}

function resolveLocalAdvisoryTimeoutMs(manifest, options = {}) {
    const explicitTimeout = Number(options.timeoutMs);
    if (Number.isFinite(explicitTimeout) && explicitTimeout > 0) return explicitTimeout;

    const profile = resolveLocalAdvisoryDeviceProfile(manifest);
    const selectedTimeout = Number(profile?.timeoutMs);
    if (Number.isFinite(selectedTimeout) && selectedTimeout > 0) return selectedTimeout;

    const profiles = manifest?.deviceProfiles;
    const profileTimeouts = Object.values(profiles ?? {})
        .map(profile => Number(profile?.timeoutMs))
        .filter(timeout => Number.isFinite(timeout) && timeout > 0);
    return profileTimeouts.length > 0 ? Math.max(...profileTimeouts) : 15000;
}

function countLocalAdvisoryInputTriangles(input) {
    if (!Array.isArray(input?.meshBuffers)) return 0;
    return input.meshBuffers.reduce((total, buffer) => {
        const indexCount = Number(buffer?.indices?.length ?? 0);
        return total + Math.floor(indexCount / 3);
    }, 0);
}

function getArrayLikeByteLength(values, bytesPerElement) {
    const byteLength = Number(values?.byteLength);
    if (Number.isFinite(byteLength) && byteLength > 0) return Math.round(byteLength);

    const length = Number(values?.length);
    if (!Number.isFinite(length) || length <= 0) return 0;
    return Math.round(length * bytesPerElement);
}

function getLocalAdvisoryInputByteLength(input) {
    const fileBytes = Number(input?.fileBytes?.byteLength ?? input?.fileBytes?.length ?? 0);
    if (Number.isFinite(fileBytes) && fileBytes > 0) return Math.round(fileBytes);

    if (!Array.isArray(input?.meshBuffers)) return 0;
    return input.meshBuffers.reduce((total, buffer) => total
        + getArrayLikeByteLength(buffer?.positions, 8)
        + getArrayLikeByteLength(buffer?.indices, 4), 0);
}

function isLocalAdvisoryInputWithinDeviceProfile(manifest, input) {
    const profile = resolveLocalAdvisoryDeviceProfile(manifest);
    if (!profile) return true;

    const maxInputBytes = Number(profile?.maxInputBytes);
    const inputBytes = getLocalAdvisoryInputByteLength(input);
    if (Number.isFinite(maxInputBytes) && maxInputBytes > 0 && inputBytes > maxInputBytes) {
        return false;
    }

    const maxTriangles = Number(profile?.maxTriangles);
    const triangleCount = countLocalAdvisoryInputTriangles(input);
    return !(Number.isFinite(maxTriangles) && maxTriangles > 0 && triangleCount > maxTriangles);
}

async function resolveAdvisoryFileBytes(options) {
    const directFileBytes = normalizeAdvisoryFileBytes(options.fileBytes);
    if (hasAdvisoryFileBytes(directFileBytes)) return directFileBytes;

    const clientUploadId = typeof options.clientUploadId === 'string'
        ? options.clientUploadId
        : typeof options.clientFileId === 'string'
            ? options.clientFileId
            : '';
    const providerName = typeof options.fileBytesProvider === 'string' ? options.fileBytesProvider : '';
    const provider = providerName && typeof window !== 'undefined'
        ? window[providerName]
        : null;
    if (!clientUploadId || typeof provider?.getFileBytes !== 'function') return null;

    return normalizeAdvisoryFileBytes(await provider.getFileBytes(clientUploadId));
}

/**
 * Runs the GeometryService-owned browser-first runtime through the same-origin BFF proxy.
 * Falls back silently to the server-only path when the manifest or worker cannot be used.
 * @param {string} canvasId
 * @param {{processCode?: string, storagePath?: string, manifestUrl?: string, assetBaseUrl?: string, timeoutMs?: number, dotNetRef?: object, fileBytes?: ArrayBuffer|Uint8Array|number[], fileName?: string, clientUploadId?: string, clientFileId?: string, fileBytesProvider?: string}} options
 * @returns {Promise<object|null>}
 */
export async function runLocalAdvisoryGeometry(canvasId, options = {}) {
    const processCode = typeof options.processCode === 'string' && options.processCode.trim()
        ? options.processCode.trim()
        : null;
    const unavailablePayload = reason => ({
        processCode,
        reason,
    });

    if (typeof fetch !== 'function' || typeof Worker === 'undefined') {
        await notifyLocalAdvisoryUnavailableDotNet(
            options.dotNetRef,
            unavailablePayload('runtime_unsupported'));
        return null;
    }

    if (!processCode) {
        await notifyLocalAdvisoryUnavailableDotNet(
            options.dotNetRef,
            unavailablePayload('process_code_missing'));
        return null;
    }

    const runId = (localAdvisoryRuns[canvasId] ?? 0) + 1;
    localAdvisoryRuns[canvasId] = runId;
    const renderLocalPanel = shouldRenderLocalAdvisoryPanel(options);

    const meshBuffers = collectAdvisoryMeshBuffers(canvasId);
    const runtimeFileBytes = await resolveAdvisoryFileBytes(options);
    const hasRuntimeFileBytes = hasAdvisoryFileBytes(runtimeFileBytes);
    if (meshBuffers.length === 0 && !hasRuntimeFileBytes) {
        await notifyLocalAdvisoryUnavailableDotNet(
            options.dotNetRef,
            unavailablePayload('no_input'));
        return null;
    }
    const runtimeFileName = typeof options.fileName === 'string' ? options.fileName : '';
    const runtimeInput = meshBuffers.length > 0
        ? { meshBuffers }
        : { fileBytes: runtimeFileBytes, fileName: runtimeFileName };
    await notifyLocalAdvisoryStartedDotNet(
        options.dotNetRef,
        {
            processCode,
            inputByteCount: getLocalAdvisoryInputByteLength(runtimeInput),
            inputTriangleCount: countLocalAdvisoryInputTriangles(runtimeInput),
        });

    if (renderLocalPanel) renderLocalAdvisoryStatus(canvasId, 'pending');
    try {
        const manifestResponse = await fetchLocalAdvisoryManifest(options.manifestUrl ?? LOCAL_ADVISORY_MANIFEST_URL);
        if (!manifestResponse?.ok || localAdvisoryRuns[canvasId] !== runId) {
            clearLocalAdvisoryPanel(canvasId);
            if (localAdvisoryRuns[canvasId] === runId) {
                await notifyLocalAdvisoryUnavailableDotNet(
                    options.dotNetRef,
                    unavailablePayload('manifest_unavailable'));
            }
            return null;
        }

        const manifest = await manifestResponse.json();
        if (Number(manifest.minFrontendApiVersion ?? 1) > LOCAL_ADVISORY_FRONTEND_API_VERSION ||
            !isBrowserFirstRuntimeContract(manifest)) {
            clearLocalAdvisoryPanel(canvasId);
            await notifyLocalAdvisoryUnavailableDotNet(
                options.dotNetRef,
                unavailablePayload('manifest_incompatible'));
            return null;
        }

        if (!isLocalAdvisoryInputWithinDeviceProfile(manifest, runtimeInput)) {
            clearLocalAdvisoryPanel(canvasId);
            await notifyLocalAdvisoryUnavailableDotNet(
                options.dotNetRef,
                unavailablePayload('input_too_large'));
            return null;
        }

        const workerUrl = resolveRuntimeAssetUrl(
            manifest.assets?.worker,
            options.assetBaseUrl ?? LOCAL_ADVISORY_ASSET_BASE_URL);
        if (!workerUrl) {
            clearLocalAdvisoryPanel(canvasId);
            await notifyLocalAdvisoryUnavailableDotNet(
                options.dotNetRef,
                unavailablePayload('asset_unavailable'));
            return null;
        }
        const wasmUrl = resolveRuntimeAssetUrl(
            manifest.assets?.wasm,
            options.assetBaseUrl ?? LOCAL_ADVISORY_ASSET_BASE_URL);

        const result = await analyzeWithLocalAdvisoryWorker(
            canvasId,
            workerUrl,
            wasmUrl,
            runtimeInput,
            processCode,
            resolveLocalAdvisoryTimeoutMs(manifest, options));
        result.storagePath = typeof options.storagePath === 'string' && options.storagePath.trim()
            ? options.storagePath.trim()
            : null;
        if (localAdvisoryRuns[canvasId] !== runId ||
            !isBrowserFirstRuntimeContract(result)) {
            clearLocalAdvisoryPanel(canvasId);
            if (localAdvisoryRuns[canvasId] === runId) {
                await notifyLocalAdvisoryUnavailableDotNet(
                    options.dotNetRef,
                    unavailablePayload('invalid_result'));
            }
            return null;
        }

        if (renderLocalPanel) renderLocalAdvisoryStatus(canvasId, 'complete', result);
        const accepted = await notifyLocalAdvisoryDotNet(options.dotNetRef, result);
        dispatchLocalAdvisoryTelemetry(canvasId, result, accepted);
        if (accepted) {
            clearLocalAdvisoryPanel(canvasId);
        }
        return result;
    } catch (_) {
        if (localAdvisoryRuns[canvasId] === runId) {
            clearLocalAdvisoryPanel(canvasId);
            await notifyLocalAdvisoryUnavailableDotNet(
                options.dotNetRef,
                unavailablePayload('worker_failed'));
        }
        return null;
    }
}

function getPointerRenderCoordinates(canvasId, pointerEvent) {
    const engine = engines[canvasId];
    const canvas = engine?.getRenderingCanvas?.() ?? document.getElementById(canvasId);
    const event = pointerEvent?.touches?.[0]
        ?? pointerEvent?.changedTouches?.[0]
        ?? pointerEvent;

    if (!canvas || !event || !Number.isFinite(event.clientX) || !Number.isFinite(event.clientY)) return null;
    const rect = canvas.getBoundingClientRect();
    if (!rect || rect.width <= 0 || rect.height <= 0) return null;

    const x = event.clientX - rect.left;
    const y = event.clientY - rect.top;
    if (x < 0 || y < 0 || x > rect.width || y > rect.height) return null;

    const renderWidth = Number(engine?.getRenderWidth?.());
    const renderHeight = Number(engine?.getRenderHeight?.());
    const scaleX = Number.isFinite(renderWidth) && renderWidth > 0
        ? renderWidth / rect.width
        : 1;
    const scaleY = Number.isFinite(renderHeight) && renderHeight > 0
        ? renderHeight / rect.height
        : 1;

    return {
        x: x * scaleX,
        y: y * scaleY,
    };
}

function getPointerInfoRenderCoordinates(canvasId, scene, pointerInfo) {
    if (pointerInfo?.event) return getPointerRenderCoordinates(canvasId, pointerInfo.event);

    return Number.isFinite(scene?.pointerX) && Number.isFinite(scene?.pointerY)
        ? { x: scene.pointerX, y: scene.pointerY }
        : null;
}

function projectWorldToRenderCoordinates(canvasId, scene, worldPos) {
    const engine = engines[canvasId];
    const cam = mainCameras[canvasId] ?? scene?.activeCamera;
    if (!engine || !cam || !worldPos) return null;
    if (typeof BABYLON.Vector3?.Project !== 'function' || typeof BABYLON.Matrix?.Identity !== 'function') return null;
    if (typeof cam.getViewMatrix !== 'function' || typeof cam.getProjectionMatrix !== 'function' || !cam.viewport) return null;

    const renderWidth = Number(engine.getRenderWidth?.());
    const renderHeight = Number(engine.getRenderHeight?.());
    if (!Number.isFinite(renderWidth) || !Number.isFinite(renderHeight) || renderWidth <= 0 || renderHeight <= 0) return null;

    try {
        const viewProjection = cam.getViewMatrix().multiply(cam.getProjectionMatrix());
        return BABYLON.Vector3.Project(
            worldPos,
            BABYLON.Matrix.Identity(),
            viewProjection,
            cam.viewport.toGlobal(renderWidth, renderHeight));
    } catch (_) {
        return null;
    }
}

function isPickProjectedNearPointer(canvasId, scene, pickResult, x, y) {
    if (!canvasId || !pickResult?.hit || !pickResult.pickedPoint) return true;

    const projected = projectWorldToRenderCoordinates(canvasId, scene, pickResult.pickedPoint);
    if (!projected || projected.z < 0 || projected.z > 1) return true;

    const engine = engines[canvasId];
    const canvas = engine?.getRenderingCanvas?.();
    const rect = canvas?.getBoundingClientRect?.();
    const renderWidth = Number(engine?.getRenderWidth?.());
    const renderHeight = Number(engine?.getRenderHeight?.());
    const scaleX = rect?.width > 0 && Number.isFinite(renderWidth) ? renderWidth / rect.width : 1;
    const scaleY = rect?.height > 0 && Number.isFinite(renderHeight) ? renderHeight / rect.height : 1;
    const tolerance = CONFIG.MEASURE.maxPickScreenDistancePx * Math.max(scaleX, scaleY, 1);

    return Math.hypot(projected.x - x, projected.y - y) <= tolerance;
}

function setAnalysisNavigationLock(canvasId, locked) {
    const pointers = mainCameras[canvasId]?.inputs?.attached?.pointers;
    if (!pointers) return;

    if (locked) {
        if (!analysisCameraButtons[canvasId]) {
            analysisCameraButtons[canvasId] = Array.isArray(pointers.buttons)
                ? [...pointers.buttons]
                : [0];
        }
        return;
    }

    if (measureStates[canvasId]?.active || thicknessStates[canvasId]?.active) return;
    const previous = analysisCameraButtons[canvasId] ?? [0];
    pointers.buttons = [...previous];
    delete analysisCameraButtons[canvasId];
}

/**
 * Safely disables edge rendering on a mesh (ignores errors for meshes without edges).
 * @param {BABYLON.AbstractMesh} mesh
 */
function safeDisableEdges(mesh) {
    try { mesh.disableEdgesRendering(); } catch (_) {}
}

/**
 * Checks if dark mode is enabled for a canvas.
 * @param {string} canvasId
 * @returns {boolean}
 */
function isDarkMode(canvasId) {
    return darkModes[canvasId] ?? false;
}

/**
 * Animates a material's alpha property for smooth fade transitions.
 * @param {BABYLON.Material} material - Material to animate
 * @param {number} fromAlpha - Starting alpha value (0-1)
 * @param {number} toAlpha - Ending alpha value (0-1)
 * @param {BABYLON.Scene} scene - Scene for animation
 * @param {number} duration - Animation duration in milliseconds (default: 200ms)
 * @returns {Promise} - Resolves when animation completes
 */
function animateMaterialAlpha(material, fromAlpha, toAlpha, scene, duration = CONFIG.ANIMATION_ALPHA_FADE_DURATION) {
    return new Promise(resolve => {
        const anim = new BABYLON.Animation(
            'alphaFade',
            'alpha',
            CONFIG.ANIMATION_FRAME_RATE,  // frames per second
            BABYLON.Animation.ANIMATIONTYPE_FLOAT,
            BABYLON.Animation.ANIMATIONLOOPMODE_CONSTANT
        );

        const keys = [
            { frame: 0, value: fromAlpha },
            { frame: (duration / 1000) * 60, value: toAlpha }
        ];
        anim.setKeys(keys);

        // Create animation group and run
        const animGroup = new BABYLON.AnimationGroup('alphaFadeGroup');
        animGroup.addTargetedAnimation(anim, material);
        animGroup.onAnimationEnd = () => {
            animGroup.dispose();
            resolve();
        };
        animGroup.play();
    });
}

// ── setRenderMode ─────────────────────────────────────────────────────────────

export function setRenderMode(canvasId, mode) {
    const scene = scenes[canvasId];
    if (!scene) return;
    activeRenderModes[canvasId] = mode;
    const origMats = originalMaterials[canvasId] ?? {};

    scene.meshes.forEach(mesh => {
        // Skip system meshes: ground grid, axis gizmo parts, bounding box lines
        if (isSystemMesh(mesh)) return;

        if (mode === 'wireframe') {
            if (!origMats[mesh.uniqueId] && mesh.material) origMats[mesh.uniqueId] = mesh.material;

            // Create per-mesh wireframe material for true triangle wireframe
            const wm = new BABYLON.StandardMaterial('wire_' + mesh.uniqueId, scene);
            const wireColor = isDarkMode(canvasId)
                ? CONFIG.WIREFRAME.colorDark
                : CONFIG.WIREFRAME.colorLight;

            wm.wireframe = true;
            // Use emissive for line color, set alpha for transparency to reduce visual density
            wm.emissiveColor = new BABYLON.Color3(wireColor.r, wireColor.g, wireColor.b);
            wm.alpha = CONFIG.WIREFRAME.faceAlpha;  // Semi-transparent lines reduce density on high-poly meshes
            wm.diffuseColor = BABYLON.Color3.Black();
            wm.specularColor = BABYLON.Color3.Black();
            wm.disableLighting = true;
            wm.backFaceCulling = false;

            mesh.material = wm;
            safeDisableEdges(mesh);

        } else if (mode === 'transparent') {
            // CAD-gray semi-transparent (X-Ray view) - uses shared material
            const tm = getOrCreateXrayMaterial(scene);
            mesh.material = tm;
            safeDisableEdges(mesh);

        } else {
            // Solid — restore the immutable baseline captured at load time.
            // Prefer defaultSolidMaterials (never overwritten by mode switches),
            // then multi-body colors, then uniform CAD gray.
            const defMat = defaultSolidMaterials[canvasId]?.get(mesh.uniqueId);
            if (defMat) {
                mesh.material = defMat;
            } else {
                const bodyMap = perCanvasBodyMap[canvasId];
                const bodyEntry = bodyMap && Array.from(bodyMap.values()).find(bd => bd.meshes.includes(mesh));
                mesh.material = bodyEntry?.colorMaterial || getCadMaterial(scene);
            }
            safeDisableEdges(mesh);
        }
    });

    // Re-apply edges after solid/transparent mode change if they were enabled.
    // Wireframe uses StandardMaterial.wireframe and disables edge rendering.
    if (mode !== 'wireframe' && edgesEnabled[canvasId]) {
        toggleEdges(canvasId, true);
    }
}

// ── setCameraPreset ───────────────────────────────────────────────────────────

export function setCameraPreset(canvasId, preset, smooth = true) {
    const cam = mainCameras[canvasId];
    const bb  = sceneBoundingBoxes[canvasId];
    if (!cam) return;

    // Kill auto-rotation instantly — zeroing current speed prevents the lerp
    // tail from drifting the camera after the preset position is applied.
    autoSpeedCurrent[canvasId] = 0;
    autoSpeedTarget[canvasId]  = SPEED_STOP;
    animStates[canvasId]       = 'interacting';

    if (smooth) {
        // Cancel any ongoing animation by setting a flag
        cam._presetAnimationCancelled = true;
        // Small delay to ensure previous animation frame is cancelled
        setTimeout(() => {
            cam._presetAnimationCancelled = false;
            applyPreset(cam, preset, smooth, canvasId);
        }, 16);
        return;
    }

    // For immediate transitions, reset to fitted view (original behavior)
    orthoZoomFactors[canvasId] = 1.0;
    if (bb) fitCameraToMesh(cam, bb, meshCenters[canvasId], canvasId);
    applyPreset(cam, preset, smooth, canvasId);
}

